def determine_caption_quality(
    is_auto_generated: bool,
    segment_count: int,
    total_duration: float,
    min_segments_for_high: int = 10,
    max_avg_duration_for_high: float = 10.0,
) -> str:
    """Determine caption quality based on source and completeness.

    Quality levels (US-007):
    - 'high': Human-uploaded captions with good completeness
    - 'medium': Auto-generated captions OR sparse human captions
    - 'low': Very sparse/incomplete captions or missing

    Assessment criteria:
    1. Source type: Human captions start at 'high', auto at 'medium'
    2. Completeness: Need at least min_segments_for_high segments for 'high'
    3. Density: Average segment duration > max_avg_duration indicates sparse captions

    Args:
        is_auto_generated: Whether captions are auto-generated by YouTube
        segment_count: Number of caption segments
        total_duration: Total caption duration in seconds
        min_segments_for_high: Minimum segments required for 'high' quality
        max_avg_duration_for_high: Max average segment duration for 'high' quality

    Returns:
        'high', 'medium', or 'low'

    Examples:
        >>> determine_caption_quality(False, 100, 300.0)  # Human, dense
        'high'
        >>> determine_caption_quality(True, 100, 300.0)   # Auto, dense
        'medium'
        >>> determine_caption_quality(False, 5, 300.0)    # Human, sparse
        'medium'
        >>> determine_caption_quality(True, 2, 60.0)      # Auto, very sparse
        'low'
    """
    # No segments = low quality (fallback/missing)
    if segment_count == 0:
        return 'low'

    # Calculate average segment duration
    avg_duration = total_duration / segment_count if segment_count > 0 else float('inf')

    # Very sparse captions (few segments or very long avg duration) = low quality
    if segment_count < 3 or (total_duration > 60 and avg_duration > 30.0):
        return 'low'

    # Auto-generated captions cap at 'medium'
    if is_auto_generated:
        # Even auto-generated needs reasonable completeness
        if segment_count >= min_segments_for_high and avg_duration <= max_avg_duration_for_high:
            return 'medium'
        return 'medium' if avg_duration <= 20.0 else 'low'

    # Human-uploaded captions
    # Need good completeness for 'high'
    if segment_count >= min_segments_for_high and avg_duration <= max_avg_duration_for_high:
        return 'high'

    # Sparse human captions = medium
    return 'medium'


class CaptionError(Exception):
    """Base exception for caption-related errors."""
    pass


class CaptionUnavailableError(CaptionError):
    """Raised when captions are not available for a video.

    This indicates the video genuinely has no captions (auto or manual),
    as opposed to a temporary fetch failure.
    """
    def __init__(self, video_id: str, reason: str = ""):
        self.video_id = video_id
        self.reason = reason
        message = f"No captions available for video {video_id}"
        if reason:
            message += f": {reason}"
        super().__init__(message)


class CaptionFetchError(CaptionError):
    """Raised when caption fetch fails due to a temporary/network error.

    This indicates a potentially retryable failure, not that captions
    don't exist.
    """
    def __init__(self, video_id: str, reason: str = ""):
        self.video_id = video_id
        self.reason = reason
        message = f"Failed to fetch captions for video {video_id}"
        if reason:
            message += f": {reason}"
        super().__init__(message)


class CaptionParseWarning(CaptionError):
    """Non-fatal warning for caption parsing issues (US-005).

    This indicates a segment could not be parsed but other segments
    may still be usable. Use for graceful degradation with partial recovery.

    Attributes:
        video_id: YouTube video ID.
        segment_index: Index of the problematic segment.
        reason: Description of the parsing issue.
    """
    def __init__(self, video_id: str, segment_index: int, reason: str = ""):
        self.video_id = video_id
        self.segment_index = segment_index
        self.reason = reason
        message = f"Parse warning for video {video_id} segment {segment_index}"
        if reason:
            message += f": {reason}"
        super().__init__(message)


class ConfigValidationError(CaptionError):
    """Raised when language configuration is invalid (US-005 Sprint 6).

    This indicates a configuration error that should be fixed before
    running the pipeline. Invalid configurations will cause silent failures
    during fetch.

    Attributes:
        field: The config field with the issue (e.g., 'fallback_languages').
        value: The invalid value.
        reason: Description of why validation failed.
        suggestion: Suggested fix for the issue.
    """
    def __init__(
        self,
        field: str,
        value: Any,
        reason: str = "",
        suggestion: str = ""
    ):
        self.field = field
        self.value = value
        self.reason = reason
        self.suggestion = suggestion
        message = f"Invalid language configuration for '{field}': {value}"
        if reason:
            message += f" - {reason}"
        if suggestion:
            message += f". Suggestion: {suggestion}"
        super().__init__(message)


