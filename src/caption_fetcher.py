@dataclass
class CaptionResult:
    """Result of a caption fetch operation.

    Attributes:
        video_id: YouTube video ID.
        segments: List of caption segments with timing.
        language: ISO 639-1 language code (e.g., 'en').
        is_auto_generated: True if auto-generated captions.
        format_source: Caption format ('vtt', 'srv3', 'json3', etc.).
        video_duration: Optional video duration for coverage calculation (US-004).
        skipped_segments: List of (index, reason) tuples for skipped segments (US-001 Sprint 7).
        partial_recovery: True when segments were skipped but result is still usable (US-001 Sprint 7).
        timing_validated: Result of timing validation, or None if not validated (US-007).
    """
    video_id: str
    segments: List[CaptionSegment] = field(default_factory=list)
    language: str = ""  # ISO 639-1 code (e.g., 'en')
    is_auto_generated: bool = False
    format_source: str = ""  # 'vtt', 'srv3', 'json3', etc.
    video_duration: Optional[float] = None  # US-004: For coverage calculation
    skipped_segments: List[tuple] = field(default_factory=list)  # US-001: (index, reason) tuples
    partial_recovery: bool = False  # US-001: True when segments skipped but result usable
    timing_validated: Optional[TimingValidationResult] = None  # US-007: Timing validation result

    @property
    def skipped_segments_count(self) -> int:
        """Backwards-compatible property for number of skipped segments."""
        return len(self.skipped_segments)

    @property
    def text(self) -> str:
        """Get full caption text concatenated."""
        return " ".join(seg.text for seg in self.segments)

    @property
    def duration(self) -> float:
        """Get total duration covered by captions."""
        if not self.segments:
            return 0.0
        return self.segments[-1].end_time - self.segments[0].start_time

    @property
    def caption_quality(self) -> str:
        """Determine caption quality based on source and completeness.

        Quality levels:
        - 'high': Human-uploaded captions (is_auto_generated=False) with good completeness
        - 'medium': Auto-generated captions with reasonable completeness
        - 'low': Missing, sparse, or fallback captions

        Quality is assessed based on:
        1. is_auto_generated flag (human > auto)
        2. Segment count (completeness indicator)
        3. Average segment duration (too long = sparse captions)

        Returns:
            'high', 'medium', or 'low'
        """
        return determine_caption_quality(
            is_auto_generated=self.is_auto_generated,
            segment_count=len(self.segments),
            total_duration=self.duration
        )

    def calculate_coverage(self, video_duration: Optional[float] = None) -> float:
        """Calculate what percentage of video duration is covered by captions (US-004).

        Coverage is calculated by summing actual caption segment durations
        (not just start-to-end span) and dividing by video duration.

        Args:
            video_duration: Video duration in seconds. If not provided, uses
                self.video_duration if set, otherwise returns 0.0.

        Returns:
            Coverage ratio from 0.0 to 1.0. Returns 0.0 if video_duration is
            unknown or zero.

        Example:
            >>> result = CaptionResult(video_id="abc", segments=[...])
            >>> coverage = result.calculate_coverage(video_duration=300.0)
            >>> print(f"{coverage:.1%}")  # "85.3%"
        """
        duration = video_duration or self.video_duration
        if not duration or duration <= 0:
            return 0.0

        if not self.segments:
            return 0.0

        # Sum actual segment durations (not just start-to-end span)
        # This handles gaps between segments correctly
        total_caption_duration = sum(
            max(0.0, seg.end_time - seg.start_time)
            for seg in self.segments
        )

        # Clamp to 1.0 in case captions overlap or extend past video
        return min(1.0, total_caption_duration / duration)

    @property
    def coverage_ratio(self) -> float:
        """Get coverage ratio using stored video_duration (US-004).

        Returns:
            Coverage ratio from 0.0 to 1.0, or 0.0 if video_duration not set.
        """
        return self.calculate_coverage()

    def validate_timing(
        self,
        video_duration: Optional[float] = None,
        max_exceed_ratio: float = 1.1,
        min_coverage_ratio: float = 0.5,
        timing_epsilon_ms: float = 100.0,
    ) -> TimingValidationResult:
        """Validate caption timestamps against video duration (US-007).

        Checks two conditions:
        1. Caption end time should not exceed video duration by more than 10% (default)
        2. Caption coverage should not be below 50% of video duration (default)

        Epsilon Tolerance Rationale:
            Floating-point precision in caption timestamps can cause false positives.
            For example, a caption ending at 299.999s in a 300s video would be flagged
            as exceeding if we use exact comparison. The timing_epsilon_ms parameter
            provides a tolerance window to handle these boundary cases.

            With timing_epsilon_ms=100.0 (default):
            - Caption at 300.05s in 300s video -> treated as ending AT duration (valid)
            - Caption at 300.15s in 300s video -> exceeds duration by 0.15s (invalid
              unless within max_exceed_ratio)

            The epsilon is applied BEFORE the max_exceed_ratio check, effectively
            snapping caption end times that are "close enough" to the video duration.

        Args:
            video_duration: Video duration in seconds. If not provided, uses
                self.video_duration if set.
            max_exceed_ratio: Maximum allowed ratio of caption_end/video_duration.
                Default 1.1 means captions can extend up to 10% beyond video.
            min_coverage_ratio: Minimum required coverage ratio.
                Default 0.5 means captions must cover at least 50% of video.
            timing_epsilon_ms: Tolerance in milliseconds for floating-point precision
                at video duration boundary. Captions ending within this epsilon of
                video duration are treated as ending exactly at duration. Default
                100.0ms handles typical floating-point rounding issues.

        Returns:
            TimingValidationResult with validation details, including
            timing_epsilon_applied showing the epsilon value used. Also stores
            result in self.timing_validated.

        Example:
            >>> result = CaptionResult(video_id="abc", segments=[...], video_duration=300.0)
            >>> validation = result.validate_timing()
            >>> if not validation.is_valid:
            ...     print(f"Warning: {validation.message}")

            # With custom epsilon for stricter validation
            >>> validation = result.validate_timing(timing_epsilon_ms=10.0)
            >>> print(f"Epsilon applied: {validation.timing_epsilon_applied}ms")
        """
        duration = video_duration or self.video_duration

        # Cannot validate without video duration
        if not duration or duration <= 0:
            result = TimingValidationResult(
                is_valid=True,  # Can't fail validation without duration
                caption_end_time=0.0,
                video_duration=0.0,
                message="Cannot validate timing: video duration unknown",
                timing_epsilon_applied=timing_epsilon_ms,
            )
            self.timing_validated = result
            return result

        # Get caption end time from last segment
        caption_end_time = self.segments[-1].end_time if self.segments else 0.0

        # Convert epsilon from milliseconds to seconds
        epsilon_seconds = timing_epsilon_ms / 1000.0

        # Apply epsilon tolerance: if caption ends within epsilon of video duration,
        # treat it as ending exactly at duration for the exceeds check
        effective_caption_end = caption_end_time
        if abs(caption_end_time - duration) <= epsilon_seconds:
            # Caption is "close enough" to video duration - snap to duration
            effective_caption_end = duration

        # Check if captions exceed video duration (using effective end time)
        exceeds_duration = effective_caption_end > (duration * max_exceed_ratio)

        # Check coverage (using last segment end time, not summed duration)
        # This is different from calculate_coverage which sums segment durations
        caption_coverage = caption_end_time / duration if duration > 0 else 0.0
        below_coverage = caption_coverage < min_coverage_ratio

        # Determine overall validity
        is_valid = not exceeds_duration and not below_coverage

        # Build message
        messages = []
        if exceeds_duration:
            exceed_pct = (caption_end_time / duration - 1.0) * 100
            messages.append(
                f"Caption end ({caption_end_time:.1f}s) exceeds video duration "
                f"({duration:.1f}s) by {exceed_pct:.1f}%"
            )
        if below_coverage:
            coverage_pct = caption_coverage * 100
            messages.append(
                f"Caption coverage ({coverage_pct:.1f}%) is below minimum "
                f"({min_coverage_ratio * 100:.0f}%)"
            )
        if is_valid:
            messages.append(f"Timing valid: captions end at {caption_end_time:.1f}s, "
                          f"video is {duration:.1f}s")

        result = TimingValidationResult(
            is_valid=is_valid,
            caption_end_time=caption_end_time,
            video_duration=duration,
            exceeds_duration=exceeds_duration,
            below_coverage=below_coverage,
            message="; ".join(messages),
            timing_epsilon_applied=timing_epsilon_ms,
        )

        self.timing_validated = result
        return result

    def to_dict(self) -> dict:
        """Convert to dictionary for serialization."""
        return {
            'video_id': self.video_id,
            'segments': [seg.to_dict() for seg in self.segments],
            'language': self.language,
            'is_auto_generated': self.is_auto_generated,
            'format_source': self.format_source,
            'caption_quality': self.caption_quality,
            'video_duration': self.video_duration,  # US-004
            'coverage_ratio': self.coverage_ratio,  # US-004
            'skipped_segments_count': self.skipped_segments_count,  # US-005
            'timing_validated': self.timing_validated.to_dict() if self.timing_validated else None,  # US-007
        }


@dataclass
class AvailableLanguage:
    """Represents an available caption language for a video."""
    code: str  # ISO 639-1 code (e.g., 'en', 'es', 'fr')
    name: str  # Human-readable name (e.g., 'English', 'Spanish')
    is_auto_generated: bool  # True if auto-generated captions


class CaptionFetcher:
    """Fetches YouTube captions using yt-dlp.

    Supports multiple caption formats (VTT, SRT, JSON3) and auto-converts
    them to a common segment format.

    Retry behavior (US-008):
    - Network errors (CaptionFetchError) are retried with exponential backoff
    - Permanent errors (CaptionUnavailableError) are NOT retried
    - After max_retries, video is marked for transcription fallback
    - Detailed logging includes video_id, error type, and retry attempt

    Example:
        fetcher = CaptionFetcher()
        result = fetcher.fetch_captions("dQw4w9WgXcQ")
        print(f"Found {len(result.segments)} segments, auto={result.is_auto_generated}")

        # List available languages first
        languages = fetcher.list_available_languages("dQw4w9WgXcQ")
        for lang in languages:
            print(f"{lang.code}: {lang.name} (auto={lang.is_auto_generated})")

        # With retry (US-008):
        try:
            result = fetcher.fetch_captions_with_retry("dQw4w9WgXcQ")
        except CaptionFetchError as e:
            # Mark for transcription fallback
            print(f"Caption fetch failed after retries: {e}")
    """

    def __init__(self, config: Optional['Config'] = None):
        """Initialize the caption fetcher.

        Args:
            config: Optional config for cookies and other settings.
        """
        self.config = config
        self._timeout = 60  # seconds

        # Retry settings from config (US-008)
        self._max_retries = 3
        self._retry_delay = 2.0
        # Format preference (US-006): json3 preferred since it's pre-structured
        self._preferred_formats = ["json3", "vtt", "srt"]
        self._default_formats = ["json3", "vtt", "srt"]  # Original static order
        # Adaptive format ordering (US-002 Sprint 7)
        self._adaptive_format_order = True
        self._using_adaptive_order = False  # Set to True when adaptive order applied
        if config:
            try:
                caption_first = getattr(config.download, 'caption_first', None)
                if caption_first:
                    self._max_retries = getattr(caption_first, 'max_retries', 3)
                    self._retry_delay = getattr(caption_first, 'retry_delay', 2.0)
                    # Also use caption_first timeout if configured
                    timeout = getattr(caption_first, 'timeout', None)
                    if timeout:
                        self._timeout = timeout
                    # Format preference (US-006)
                    preferred_formats = getattr(caption_first, 'preferred_formats', None)
                    if preferred_formats and isinstance(preferred_formats, list):
                        self._preferred_formats = preferred_formats
                        self._default_formats = list(preferred_formats)
                    # Adaptive format ordering (US-002 Sprint 7)
                    self._adaptive_format_order = getattr(
                        caption_first, 'adaptive_format_order', True
                    )
            except AttributeError:
                pass

    def apply_adaptive_format_order(
        self,
        metrics: Optional['CaptionMetrics'] = None,
        cache: Optional['CaptionCache'] = None,
    ) -> List[str]:
        """Apply adaptive format ordering based on historical success rates (US-002 Sprint 7).

        When adaptive_format_order is enabled, this method reorders the format
        preference list based on historical success rates. Formats with higher
        success rates are tried first, reducing average fetch latency.

        Args:
            metrics: CaptionMetrics with format_success_counts data. If provided,
                     uses these counts directly.
            cache: CaptionCache to load historical format statistics from.
                   Used if metrics is None or has no data.

        Returns:
            List of format names in the new order (for logging purposes).

        Example:
            >>> fetcher = CaptionFetcher(config)
            >>> cache = CaptionCache(config.download.caption_first)
            >>> new_order = fetcher.apply_adaptive_format_order(cache=cache)
            >>> print(f"Adaptive format order: {new_order}")
            Adaptive format order: ['vtt', 'json3', 'srt']

        Note:
            This method must be called before fetch operations to enable
            adaptive ordering. If not called, static preferred_formats is used.
        """
        if not self._adaptive_format_order:
            logger.debug("Adaptive format order disabled, using static order")
            return list(self._preferred_formats)

        # Get historical format counts
        format_counts: Dict[str, int] = {}

        # Priority 1: Use metrics if provided and has data
        if metrics is not None:
            with metrics._lock:
                format_counts = dict(metrics.format_success_counts)

        # Priority 2: Load from cache if metrics is empty
        if not format_counts and cache is not None:
            format_counts = cache.load_format_statistics()

        # If no historical data, use default order
        if not format_counts:
            logger.debug("No historical format data, using default order")
            return list(self._default_formats)

        # Calculate optimal order using a temporary metrics object
        temp_metrics = CaptionMetrics()
        temp_metrics.format_success_counts = format_counts

        optimal_order = temp_metrics.get_optimal_format_order(
            default_formats=self._default_formats
        )

        # Calculate success rates for logging
        total = sum(format_counts.values())
        rates = {
            fmt: round(100.0 * format_counts.get(fmt, 0) / total, 0)
            for fmt in optimal_order
            if format_counts.get(fmt, 0) > 0
        }

        # Only apply if order actually changed
        if optimal_order != self._default_formats:
            self._preferred_formats = optimal_order
            self._using_adaptive_order = True

            # Log with format and success rate
            rate_strs = [f"{fmt} ({rates[fmt]:.0f}%)" for fmt in optimal_order if fmt in rates]
            if rate_strs:
                logger.info(f"Adaptive format order: {', '.join(rate_strs)}")
            else:
                logger.info(f"Adaptive format order: {optimal_order}")
        else:
            logger.debug("Adaptive order matches default order")

        return optimal_order

    def list_available_languages(self, video_id: str) -> List[AvailableLanguage]:
        """List available caption languages for a YouTube video.

        Uses yt-dlp to query subtitle metadata without downloading.
        Returns both manual and auto-generated caption languages.

        Args:
            video_id: YouTube video ID (11 characters).

        Returns:
            List of AvailableLanguage objects, sorted with manual captions first,
            then auto-generated. Within each group, sorted by language code.

        Raises:
            CaptionFetchError: If unable to query video metadata.

        Example:
            languages = fetcher.list_available_languages("dQw4w9WgXcQ")
            # [AvailableLanguage(code='en', name='English', is_auto_generated=False),
            #  AvailableLanguage(code='en', name='English (auto-generated)', is_auto_generated=True)]
        """
        if not self._is_valid_video_id(video_id):
            raise CaptionFetchError(video_id, f"Invalid video ID format: {video_id}")

        video_url = f"https://www.youtube.com/watch?v={video_id}"

        cmd = [
            'yt-dlp',
            video_url,
            '--skip-download',
            '--list-subs',
            '--no-playlist',
            '--no-warnings',
        ]

        # Add cookies if configured
        cmd.extend(self._get_cookies_args())

        try:
            result = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                timeout=self._timeout
            )

            # Parse the output to extract available languages
            return self._parse_list_subs_output(result.stdout, result.stderr)

        except subprocess.TimeoutExpired:
            raise CaptionFetchError(video_id, f"Timeout after {self._timeout}s")
        except Exception as e:
            raise CaptionFetchError(video_id, str(e))

    def _parse_list_subs_output(
        self,
        stdout: str,
        stderr: str
    ) -> List[AvailableLanguage]:
        """Parse yt-dlp --list-subs output to extract available languages.

        The output format looks like:
            [info] Available subtitles for VIDEO_ID:
            Language  Name                 Formats
            en        English              vtt, ttml, srv3, srv2, srv1, json3
            es        Spanish              vtt, ttml, srv3, srv2, srv1, json3

            [info] Available automatic captions for VIDEO_ID:
            Language  Name                              Formats
            en        English (auto-generated)          vtt, ttml, srv3, srv2, srv1, json3

        Args:
            stdout: Standard output from yt-dlp.
            stderr: Standard error from yt-dlp.

        Returns:
            List of AvailableLanguage objects.
        """
        languages = []
        combined_output = stdout + "\n" + stderr

        # Track which section we're in
        in_manual_section = False
        in_auto_section = False

        # Pattern to match language lines (after header)
        # Format: "en        English              vtt, ttml, ..."
        lang_line_pattern = re.compile(
            r'^([a-z]{2,3}(?:-[A-Za-z]{2,4})?)\s+(.+?)\s+(?:vtt|ttml|srv|json)',
            re.IGNORECASE
        )

        for line in combined_output.split('\n'):
            line = line.strip()

            # Detect section headers
            if 'Available subtitles' in line:
                in_manual_section = True
                in_auto_section = False
                continue
            elif 'Available automatic captions' in line:
                in_manual_section = False
                in_auto_section = True
                continue
            elif line.startswith('[info]') or line.startswith('Language'):
                # Skip info lines and headers
                continue
            elif not line:
                # Empty line might end a section
                continue

            # Try to parse language line
            match = lang_line_pattern.match(line)
            if match:
                lang_code = match.group(1).lower()
                lang_name = match.group(2).strip()

                # Determine if auto-generated
                is_auto = in_auto_section or '(auto' in lang_name.lower()

                # Clean up the name
                if '(auto-generated)' in lang_name:
                    display_name = lang_name
                elif is_auto:
                    display_name = f"{lang_name} (auto-generated)"
                else:
                    display_name = lang_name

                languages.append(AvailableLanguage(
                    code=lang_code,
                    name=display_name,
                    is_auto_generated=is_auto
                ))

        # Sort: manual captions first, then auto-generated, alphabetically within each
        languages.sort(key=lambda x: (x.is_auto_generated, x.code))

        logger.debug(f"Found {len(languages)} available caption languages")
        return languages

    def has_captions(self, video_id: str) -> bool:
        """Check if a video has any captions available (US-008).

        This is a lightweight check that queries subtitle availability without
        downloading caption content. Uses list_available_languages() internally.

        Use this for pre-filtering video candidates before full caption fetch,
        which avoids wasted network calls for videos without captions.

        Args:
            video_id: YouTube video ID (11 characters).

        Returns:
            True if at least one caption language is available (manual or auto),
            False if no captions are available.

        Raises:
            CaptionFetchError: If unable to query video metadata.

        Example:
            if fetcher.has_captions("dQw4w9WgXcQ"):
                result = fetcher.fetch_captions("dQw4w9WgXcQ")
            else:
                print("No captions available, will use transcription fallback")
        """
        languages = self.list_available_languages(video_id)
        has_any = len(languages) > 0
        logger.debug(f"Caption availability check for {video_id}: {'available' if has_any else 'unavailable'}")
        return has_any

    def select_best_language(
        self,
        available: List[AvailableLanguage],
        preferred: Optional[str] = None,
        fallback_to_english: bool = True,
        prefer_manual: bool = True,
        fallback_languages: Optional[List[str]] = None
    ) -> Optional[AvailableLanguage]:
        """Select the best language from available options using fallback chain.

        Implements the fallback chain (US-003):
        1. Preferred language (manual if prefer_manual, else any)
        2. Configured fallback_languages in order (from config or param)
        3. English 'en' (if fallback_to_english and not already tried)
        4. Any available language (manual if prefer_manual, else any)

        Args:
            available: List of available languages from list_available_languages().
            preferred: Preferred language code (e.g., 'en', 'es'). If None, uses
                       config.download.caption_first.preferred_language or
                       config.transcription.language.
            fallback_to_english: If True, fall back to English if preferred unavailable.
            prefer_manual: If True, prefer manual captions over auto-generated.
            fallback_languages: Optional list of fallback language codes. If None,
                               uses config.download.caption_first.fallback_languages.

        Returns:
            Selected AvailableLanguage, or None if no languages available.

        Example:
            languages = fetcher.list_available_languages("dQw4w9WgXcQ")
            best = fetcher.select_best_language(languages, preferred='es',
                                                fallback_languages=['pt', 'en', 'fr'])
            if best:
                result = fetcher.fetch_captions("dQw4w9WgXcQ", language=best.code)
        """
        if not available:
            logger.warning("No caption languages available to select from")
            return None

        # Determine preferred language from args or config
        if preferred is None:
            preferred = self._get_preferred_language_from_config()

        # Get fallback chain from args or config
        if fallback_languages is None:
            fallback_languages = self._get_fallback_languages_from_config()

        logger.debug(f"Selecting caption language: preferred={preferred}, "
                    f"fallback_chain={fallback_languages}, "
                    f"fallback_english={fallback_to_english}, prefer_manual={prefer_manual}")

        def find_language(code: str, manual_only: bool = False) -> Optional[AvailableLanguage]:
            """Find a language by code, optionally filtering to manual only."""
            for lang in available:
                if lang.code.lower() == code.lower():
                    if manual_only and lang.is_auto_generated:
                        continue
                    return lang
            return None

        def try_language(code: str, position: str) -> Optional[AvailableLanguage]:
            """Try to find a language, preferring manual if configured.

            Returns the language if found, logging which position in the chain.
            """
            if prefer_manual:
                result = find_language(code, manual_only=True)
                if result:
                    logger.info(f"Selected '{result.code}' (manual) from {position}")
                    return result

            result = find_language(code, manual_only=False)
            if result:
                auto_str = 'auto' if result.is_auto_generated else 'manual'
                logger.info(f"Selected '{result.code}' ({auto_str}) from {position}")
                return result
            return None

        # Build the complete fallback chain with positions tracked
        languages_tried: set = set()

        # Step 1: Try preferred language
        if preferred:
            result = try_language(preferred, "preferred language")
            if result:
                return result
            languages_tried.add(preferred.lower())
            logger.debug(f"Preferred language '{preferred}' not available")

        # Step 2: Try configured fallback languages in order
        if fallback_languages:
            for idx, fallback_code in enumerate(fallback_languages, start=1):
                if fallback_code.lower() in languages_tried:
                    continue  # Skip already-tried languages
                result = try_language(fallback_code, f"fallback chain position {idx}")
                if result:
                    return result
                languages_tried.add(fallback_code.lower())
                logger.debug(f"Fallback language '{fallback_code}' (position {idx}) not available")

        # Step 3: Fall back to English (if not already tried and enabled)
        if fallback_to_english and 'en' not in languages_tried:
            result = try_language('en', "English fallback")
            if result:
                return result
            languages_tried.add('en')
            logger.debug("English not available")

        # Step 4: Fall back to any available language
        if prefer_manual:
            manual_langs = [l for l in available if not l.is_auto_generated]
            if manual_langs:
                result = manual_langs[0]  # Already sorted by code
                logger.info(f"Selected '{result.code}' (manual) from any available fallback")
                return result

        if available:
            result = available[0]  # Already sorted: manual first, then auto
            auto_str = 'auto' if result.is_auto_generated else 'manual'
            logger.info(f"Selected '{result.code}' ({auto_str}) from any available fallback")
            return result

        logger.warning("No suitable caption language found")
        return None

    def _get_preferred_language_from_config(self) -> str:
        """Get preferred language from config.

        Checks in order:
        1. config.download.caption_first.preferred_language
        2. config.transcription.language
        3. Default to 'en'

        Returns:
            Language code (ISO 639-1).
        """
        if not self.config:
            return 'en'

        try:
            # First try caption_first.preferred_language
            caption_first = getattr(self.config.download, 'caption_first', None)
            if caption_first:
                preferred = getattr(caption_first, 'preferred_language', None)
                if preferred:
                    return preferred

            # Then try transcription.language
            transcription = getattr(self.config, 'transcription', None)
            if transcription:
                lang = getattr(transcription, 'language', None)
                if lang:
                    return lang
        except AttributeError:
            pass

        return 'en'

    def _get_fallback_languages_from_config(self) -> List[str]:
        """Get fallback language chain from config (US-003).

        Returns:
            List of language codes (ISO 639-1), empty if not configured.
        """
        if not self.config:
            return []

        try:
            caption_first = getattr(self.config.download, 'caption_first', None)
            if caption_first:
                fallback_langs = getattr(caption_first, 'fallback_languages', None)
                if fallback_langs and isinstance(fallback_langs, list):
                    return fallback_langs
        except AttributeError:
            pass

        return []

    def fetch_captions_auto_language(
        self,
        video_id: str,
        preferred_language: Optional[str] = None
    ) -> CaptionResult:
        """Fetch captions with automatic language selection.

        Combines list_available_languages and fetch_captions with intelligent
        language selection based on config and availability.

        Args:
            video_id: YouTube video ID.
            preferred_language: Optional override for preferred language.

        Returns:
            CaptionResult with captions in the best available language.

        Raises:
            CaptionUnavailableError: If no captions available in any language.
            CaptionFetchError: If fetch fails due to network/temporary error.
        """
        # List available languages
        available = self.list_available_languages(video_id)

        if not available:
            raise CaptionUnavailableError(
                video_id,
                "No captions available in any language"
            )

        # Select best language
        prefer_manual = True
        if self.config:
            caption_first = getattr(self.config.download, 'caption_first', None)
            if caption_first:
                prefer_manual = getattr(caption_first, 'prefer_human_captions', True)

        selected = self.select_best_language(
            available,
            preferred=preferred_language,
            fallback_to_english=True,
            prefer_manual=prefer_manual
        )

        if not selected:
            raise CaptionUnavailableError(
                video_id,
                "No suitable language found despite available captions"
            )

        # Fetch captions in selected language
        return self.fetch_captions(
            video_id,
            language=selected.code,
            prefer_manual=not selected.is_auto_generated
        )

    def fetch_captions_with_retry(
        self,
        video_id: str,
        language: str = "en",
        prefer_manual: bool = True,
        max_retries: Optional[int] = None,
        retry_delay: Optional[float] = None
    ) -> CaptionResult:
        """Fetch captions with exponential backoff retry logic (US-008).

        Retries on network/temporary errors (CaptionFetchError) but NOT on
        permanent errors (CaptionUnavailableError - when captions don't exist).

        Args:
            video_id: YouTube video ID (11 characters).
            language: Preferred language code (ISO 639-1).
            prefer_manual: If True, prefer manually uploaded captions over auto-generated.
            max_retries: Override max retry attempts (default: config or 3).
            retry_delay: Override base delay between retries (default: config or 2.0s).

        Returns:
            CaptionResult with parsed segments and metadata.

        Raises:
            CaptionUnavailableError: If no captions exist (NOT retried).
            CaptionFetchError: If all retries fail due to network/temporary errors.

        Example:
            try:
                result = fetcher.fetch_captions_with_retry("dQw4w9WgXcQ")
            except CaptionFetchError as e:
                # Mark for transcription fallback after max retries
                needs_transcription.append(video_id)
        """
        retries = max_retries if max_retries is not None else self._max_retries
        delay = retry_delay if retry_delay is not None else self._retry_delay

        return self._with_retry(
            func=lambda: self.fetch_captions(video_id, language, prefer_manual),
            video_id=video_id,
            operation="fetch_captions",
            max_retries=retries,
            retry_delay=delay
        )

