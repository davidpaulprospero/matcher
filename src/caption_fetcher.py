class CaptionCache(BaseCache):
    """Cache for YouTube captions, enabling cross-project reuse.

    Caches fetched captions by video_id + language code to avoid
    re-fetching the same captions across different projects.

    Features:
    - JSON index for fast lookups
    - Age-based expiration (configurable days)
    - Cache key: video_id_language (e.g., 'dQw4w9WgXcQ_en')
    - Stores caption text, timing info, is_auto_generated, fetch_timestamp

    Usage:
        cache = CaptionCache(config.download.caption_first)

        # Check cache before fetching
        cached = cache.get_caption("dQw4w9WgXcQ", "en")
        if cached:
            result = cached.to_caption_result()
        else:
            result = fetcher.fetch_captions("dQw4w9WgXcQ")
            cache.store(result)

    Example with CaptionFetcher:
        fetcher = CaptionFetcher(config)
        cache = CaptionCache(config.download.caption_first)

        def fetch_with_cache(video_id: str, language: str = "en"):
            cached = cache.get_caption(video_id, language)
            if cached:
                return cached.to_caption_result()
            result = fetcher.fetch_captions(video_id, language=language)
            cache.store(result)
            return result
    """

    def __init__(self, config: Optional['CaptionFirstConfig'] = None):
        """Initialize the caption cache.

        Args:
            config: CaptionFirstConfig with cache settings. If None, uses defaults.
        """
        # Get config values with defaults
        if config:
            cache_dir = getattr(config, 'cache_dir', '~/.matcher_caption_cache')
            max_age_days = getattr(config, 'max_cache_age_days', 30)
            self.enabled = getattr(config, 'cache_captions', True)
            # Cache validation settings (US-008 Sprint 6)
            self.validation_mode = getattr(config, 'cache_validation', 'warn')
            self.validation_tolerance = getattr(config, 'cache_validation_tolerance', 0.2)
        else:
            cache_dir = '~/.matcher_caption_cache'
            max_age_days = 30
            self.enabled = True
            self.validation_mode = 'warn'
            self.validation_tolerance = 0.2

        # Expand ~ in cache_dir
        cache_dir = Path(os.path.expanduser(cache_dir))

        # Convert max_age_days to TTL seconds (0 = no expiration)
        ttl_seconds = max_age_days * 24 * 3600 if max_age_days > 0 else 0

        # Initialize BaseCache
        super().__init__(
            cache_dir=cache_dir,
            index_name="caption_cache_index.json",
            ttl_seconds=ttl_seconds,
            auto_save=True
        )

        self.max_age_days = max_age_days

        logger.debug(f"CaptionCache initialized: dir={cache_dir}, "
                    f"ttl={max_age_days} days, enabled={self.enabled}, "
                    f"validation={self.validation_mode}")

    def _make_cache_key(self, video_id: str, language: str) -> str:
        """Create cache key from video_id and language.

        Args:
            video_id: YouTube video ID (11 characters).
            language: ISO 639-1 language code (e.g., 'en').

        Returns:
            Cache key in format 'video_id_language' (e.g., 'dQw4w9WgXcQ_en').
        """
        return f"{video_id}_{language}"

    def _serialize_entry(self, entry: CacheEntry) -> Dict[str, Any]:
        """Serialize CachedCaption to dict."""
        return {
            'data': entry.data,  # CachedCaption.to_dict()
            'cached_at': entry.cached_at,
            'metadata': entry.metadata
        }

    def _deserialize_entry(self, data: Dict[str, Any]) -> CacheEntry:
        """Deserialize dict to CachedCaption entry."""
        return CacheEntry(
            data=data.get('data', {}),
            cached_at=data.get('cached_at', 0.0),
            key='',
            metadata=data.get('metadata', {})
        )

    def validate_cache_entry(
        self,
        cached: CachedCaption,
        video_id: str,
        language: str
    ) -> CacheValidationResult:
        """Validate a cached caption entry for integrity (US-008 Sprint 6).

        Checks:
        1. video_id matches requested video_id
        2. language matches requested language
        3. segment_count is within tolerance of expected count (based on duration)

        The expected segment count is estimated as: duration / 3 (seconds per segment)
        since typical caption segments are ~3 seconds long.

        Args:
            cached: CachedCaption to validate.
            video_id: Expected video ID.
            language: Expected language code.

        Returns:
            CacheValidationResult with is_valid=True if all checks pass,
            or is_valid=False with reason explaining the failure.

        Example:
            >>> cache = CaptionCache(config)
            >>> cached = cache.get_caption("dQw4w9WgXcQ", "en")
            >>> if cached:
            ...     result = cache.validate_cache_entry(cached, "dQw4w9WgXcQ", "en")
            ...     if not result.is_valid:
            ...         logger.warning(f"Cache validation failed: {result.reason}")
        """
        # Check video_id match
        if cached.video_id != video_id:
            return CacheValidationResult(
                is_valid=False,
                video_id=video_id,
                language=language,
                reason=f"video_id mismatch: cached={cached.video_id}, expected={video_id}",
            )

        # Check language match
        if cached.language != language:
            return CacheValidationResult(
                is_valid=False,
                video_id=video_id,
                language=language,
                reason=f"language mismatch: cached={cached.language}, expected={language}",
            )

        # Check segment count consistency (if duration is available)
        actual_count = len(cached.segments)
        if cached.duration > 0:
            # Expect ~1 segment per 3 seconds of video
            expected_count = max(1, int(cached.duration / 3))
            deviation = abs(actual_count - expected_count) / max(expected_count, 1)

            if deviation > self.validation_tolerance:
                return CacheValidationResult(
                    is_valid=False,
                    video_id=video_id,
                    language=language,
                    reason=(
                        f"segment_count deviation {deviation:.1%} exceeds tolerance "
                        f"{self.validation_tolerance:.0%}: expected ~{expected_count}, "
                        f"got {actual_count}"
                    ),
                    expected_segment_count=expected_count,
                    actual_segment_count=actual_count,
                    segment_count_deviation=deviation,
                )
        else:
            # No duration info - can't validate segment count, just check non-empty
            if actual_count == 0:
                return CacheValidationResult(
                    is_valid=False,
                    video_id=video_id,
                    language=language,
                    reason="cached caption has 0 segments",
                    actual_segment_count=0,
                )

        # All checks passed
        return CacheValidationResult(
            is_valid=True,
            video_id=video_id,
            language=language,
            actual_segment_count=actual_count,
            expected_segment_count=int(cached.duration / 3) if cached.duration > 0 else None,
        )

    def get_caption(self, video_id: str, language: str) -> Optional[CachedCaption]:
        """Get cached caption for a video and language.

        Args:
            video_id: YouTube video ID.
            language: ISO 639-1 language code.

        Returns:
            CachedCaption if found and valid, None otherwise.
        """
        if not self.enabled:
            return None

        key = self._make_cache_key(video_id, language)
        entry = self.get(key)

        if entry is None:
            logger.debug(f"Caption cache miss: {key}")
            return None

        try:
            cached = CachedCaption.from_dict(entry.data)
            logger.debug(f"Caption cache hit: {key} "
                        f"({len(cached.segments)} segments, "
                        f"auto={cached.is_auto_generated})")
            return cached
        except Exception as e:
            logger.warning(f"Failed to deserialize cached caption {key}: {e}")
            self.delete(key)
            return None

    def get_validated_caption(
        self,
        video_id: str,
        language: str,
        metrics: Optional['CaptionMetrics'] = None
    ) -> tuple[Optional[CachedCaption], Optional[CacheValidationResult]]:
        """Get cached caption with validation (US-008 Sprint 6).

        Retrieves cached caption and validates its integrity based on the
        configured validation_mode:
        - 'skip': No validation, returns cached data as-is
        - 'warn': Validates and logs warning on failure, returns None
        - 'strict': Validates and returns None on failure (rejects cache)

        Args:
            video_id: YouTube video ID.
            language: ISO 639-1 language code.
            metrics: Optional CaptionMetrics to track validation results.

        Returns:
            Tuple of (CachedCaption or None, CacheValidationResult or None).
            First element is the cached data (None if miss or validation failed).
            Second element is the validation result (None if skip mode or miss).

        Example:
            >>> cache = CaptionCache(config)
            >>> cached, validation = cache.get_validated_caption("dQw4w9WgXcQ", "en")
            >>> if cached:
            ...     result = cached.to_caption_result()
            ... elif validation and not validation.is_valid:
            ...     logger.info(f"Cache rejected: {validation.reason}")
        """
        # Get raw cached data
        cached = self.get_caption(video_id, language)
        if cached is None:
            return None, None

        # Skip validation if mode is 'skip'
        if self.validation_mode == 'skip':
            return cached, None

        # Validate the cached entry
        validation_result = self.validate_cache_entry(cached, video_id, language)

        # Track validation results in metrics
        if metrics is not None:
            metrics.record_cache_validation(validation_result)

        if validation_result.is_valid:
            return cached, validation_result

        # Handle validation failure based on mode
        key = self._make_cache_key(video_id, language)
        if self.validation_mode == 'strict':
            logger.warning(
                f"Cache validation REJECTED {key}: {validation_result.reason}"
            )
            # Don't delete in strict mode - let user investigate
            return None, validation_result
        else:  # 'warn' mode
            logger.warning(
                f"Cache validation failed {key}: {validation_result.reason} "
                f"(will re-fetch)"
            )
            # Invalidate the corrupted entry so it gets re-fetched
            self.delete(key)
            return None, validation_result

    def store(self, result: CaptionResult) -> bool:
        """Store a CaptionResult in the cache.

        Args:
            result: CaptionResult to cache.

        Returns:
            True if stored successfully, False otherwise.
        """
        if not self.enabled:
            return False

        if not result.segments:
            logger.debug(f"Not caching empty caption result for {result.video_id}")
            return False

        key = self._make_cache_key(result.video_id, result.language)

        cached = CachedCaption(
            video_id=result.video_id,
            language=result.language,
            segments=[seg.to_dict() for seg in result.segments],
            is_auto_generated=result.is_auto_generated,
            format_source=result.format_source,
            fetch_timestamp=time.time(),
            duration=result.duration,
        )

        self.set(key, cached.to_dict())

        logger.info(f"Cached captions: {key} "
                   f"({len(result.segments)} segments, "
                   f"duration={result.duration:.1f}s, "
                   f"auto={result.is_auto_generated})")
        return True

    def get_or_fetch(
        self,
        fetcher: 'CaptionFetcher',
        video_id: str,
        language: str = "en",
        prefer_manual: bool = True
    ) -> CaptionResult:
        """Get from cache or fetch and cache.

        Convenience method that combines cache lookup and fetching.

        Args:
            fetcher: CaptionFetcher instance to use for fetching.
            video_id: YouTube video ID.
            language: Preferred language code.
            prefer_manual: Prefer manual captions over auto-generated.

        Returns:
            CaptionResult from cache or freshly fetched.

        Raises:
            CaptionUnavailableError: If no captions exist.
            CaptionFetchError: If fetch fails due to network/temporary error.
        """
        # Check cache first
        cached = self.get_caption(video_id, language)
        if cached:
            return cached.to_caption_result()

        # Fetch and cache
        result = fetcher.fetch_captions(video_id, language=language, prefer_manual=prefer_manual)
        self.store(result)
        return result

    def get_or_fetch_with_retry(
        self,
        fetcher: 'CaptionFetcher',
        video_id: str,
        language: str = "en",
        prefer_manual: bool = True,
        max_retries: Optional[int] = None,
        retry_delay: Optional[float] = None
    ) -> CaptionResult:
        """Get from cache or fetch with retry logic and cache (US-008).

        Combines cache lookup with fetch retry logic. Uses exponential backoff
        for network errors (CaptionFetchError) but NOT for permanent errors
        (CaptionUnavailableError).

        Args:
            fetcher: CaptionFetcher instance to use for fetching.
            video_id: YouTube video ID.
            language: Preferred language code.
            prefer_manual: Prefer manual captions over auto-generated.
            max_retries: Override max retry attempts (default: fetcher config).
            retry_delay: Override base delay between retries (default: fetcher config).

        Returns:
            CaptionResult from cache or freshly fetched.

        Raises:
            CaptionUnavailableError: If no captions exist (NOT retried).
            CaptionFetchError: If all retries fail due to network/temporary errors.

        Example:
            cache = CaptionCache(config.download.caption_first)
            fetcher = CaptionFetcher(config)
            try:
                result = cache.get_or_fetch_with_retry(fetcher, "dQw4w9WgXcQ")
            except CaptionFetchError:
                # Mark for transcription fallback
                needs_transcription.append("dQw4w9WgXcQ")
        """
        # Check cache first
        cached = self.get_caption(video_id, language)
        if cached:
            return cached.to_caption_result()

        # Fetch with retry and cache
        result = fetcher.fetch_captions_with_retry(
            video_id,
            language=language,
            prefer_manual=prefer_manual,
            max_retries=max_retries,
            retry_delay=retry_delay
        )
        self.store(result)
        return result

    def invalidate(self, video_id: str, language: Optional[str] = None) -> int:
        """Invalidate cached captions for a video.

        Args:
            video_id: YouTube video ID.
            language: If provided, only invalidate for this language.
                     If None, invalidate all languages for this video.

        Returns:
            Number of cache entries invalidated.
        """
        if language:
            key = self._make_cache_key(video_id, language)
            if self.delete(key):
                logger.debug(f"Invalidated caption cache: {key}")
                return 1
            return 0

        # Invalidate all languages for this video
        invalidated = 0
        for key in list(self.index.keys()):
            if key.startswith(f"{video_id}_"):
                self.delete(key)
                invalidated += 1

        if invalidated:
            logger.debug(f"Invalidated {invalidated} caption cache entries for {video_id}")

        return invalidated

    def save_format_statistics(self, format_success_counts: Dict[str, int]) -> bool:
        """Save format success counts to cache metadata (US-002 Sprint 7).

        Persists format success statistics for cross-run learning.
        These statistics enable adaptive format ordering, trying
        historically successful formats first.

        Args:
            format_success_counts: Dict mapping format name -> success count.
                                   Example: {'json3': 95, 'vtt': 80, 'srt': 25}

        Returns:
            True if saved successfully, False otherwise.

        Example:
            >>> cache = CaptionCache(config)
            >>> metrics = CaptionMetrics()
            >>> # After batch fetch...
            >>> cache.save_format_statistics(metrics.format_success_counts)
            True
        """
        if not self.enabled:
            return False

        try:
            # Store in a special metadata entry
            metadata_key = "__format_statistics__"
            self.index[metadata_key] = {
                'format_success_counts': format_success_counts,
                'updated_at': time.time(),
                'total_samples': sum(format_success_counts.values()),
            }
            if self.auto_save:
                self._save_index()

            logger.debug(f"Saved format statistics: {format_success_counts}")
            return True
        except Exception as e:
            logger.warning(f"Failed to save format statistics: {e}")
            return False

    def load_format_statistics(self) -> Dict[str, int]:
        """Load format success counts from cache metadata (US-002 Sprint 7).

        Retrieves persisted format success statistics for adaptive ordering.
        Returns empty dict if no historical data available.

        Returns:
            Dict mapping format name -> success count.
            Empty dict if no historical data exists.

        Example:
            >>> cache = CaptionCache(config)
            >>> historical = cache.load_format_statistics()
            >>> if historical:
            ...     metrics.format_success_counts = historical
            ...     optimal_order = metrics.get_optimal_format_order()
        """
        if not self.enabled:
            return {}

        try:
            metadata_key = "__format_statistics__"
            metadata = self.index.get(metadata_key, {})
            format_counts = metadata.get('format_success_counts', {})

            if format_counts:
                total = metadata.get('total_samples', sum(format_counts.values()))
                logger.debug(f"Loaded format statistics: {format_counts} ({total} samples)")

            return format_counts
        except Exception as e:
            logger.warning(f"Failed to load format statistics: {e}")
            return {}

    def save_channel_patterns(
        self,
        patterns: Dict[str, 'ChannelCaptionPattern']
    ) -> bool:
        """Save channel caption patterns to cache metadata (US-006 Sprint 7).

        Persists channel-level caption availability patterns for cross-run
        optimization. These patterns enable batch pre-check grouping where
        channels with high confidence patterns skip individual pre-checks.

        Args:
            patterns: Dict mapping channel_id -> ChannelCaptionPattern.

        Returns:
            True if saved successfully, False otherwise.

        Example:
            >>> cache = CaptionCache(config)
            >>> patterns = {
            ...     "UCabc": ChannelCaptionPattern("UCabc", 10, 9, 0.9, time.time()),
            ...     "UCdef": ChannelCaptionPattern("UCdef", 5, 0, 0.0, time.time()),
            ... }
            >>> cache.save_channel_patterns(patterns)
            True
        """
        if not self.enabled:
            return False

        try:
            metadata_key = "__channel_patterns__"
            self.index[metadata_key] = {
                'patterns': {
                    cid: pattern.to_dict()
                    for cid, pattern in patterns.items()
                },
                'updated_at': time.time(),
                'total_channels': len(patterns),
            }
            if self.auto_save:
                self._save_index()

            logger.debug(f"Saved {len(patterns)} channel caption patterns")
            return True
        except Exception as e:
            logger.warning(f"Failed to save channel patterns: {e}")
            return False

    def load_channel_patterns(self) -> Dict[str, 'ChannelCaptionPattern']:
        """Load channel caption patterns from cache metadata (US-006 Sprint 7).

        Retrieves persisted channel-level caption availability patterns for
        batch pre-check optimization. Channels with >90% confidence and
        sufficient samples can skip individual pre-checks.

        Returns:
            Dict mapping channel_id -> ChannelCaptionPattern.
            Empty dict if no historical data exists.

        Example:
            >>> cache = CaptionCache(config)
            >>> patterns = cache.load_channel_patterns()
            >>> for cid, pattern in patterns.items():
            ...     if pattern.success_rate > 0.9 and pattern.videos_checked >= 5:
            ...         print(f"Channel {cid}: high confidence ({pattern.success_rate:.0%})")
        """
        if not self.enabled:
            return {}

        try:
            metadata_key = "__channel_patterns__"
            metadata = self.index.get(metadata_key, {})
            patterns_data = metadata.get('patterns', {})

            patterns = {}
            for cid, data in patterns_data.items():
                patterns[cid] = ChannelCaptionPattern.from_dict(data)

            if patterns:
                total_channels = metadata.get('total_channels', len(patterns))
                logger.debug(f"Loaded {total_channels} channel caption patterns")

            return patterns
        except Exception as e:
            logger.warning(f"Failed to load channel patterns: {e}")
            return {}

    def get_channel_pattern(self, channel_id: str) -> Optional['ChannelCaptionPattern']:
        """Get a single channel's caption pattern (US-006 Sprint 7).

        Convenience method to retrieve pattern for a specific channel.

        Args:
            channel_id: YouTube channel ID (UCxxxx format).

        Returns:
            ChannelCaptionPattern if found, None otherwise.
        """
        patterns = self.load_channel_patterns()
        return patterns.get(channel_id)

    def update_channel_pattern(
        self,
        channel_id: str,
        has_captions: bool
    ) -> 'ChannelCaptionPattern':
        """Update a channel's caption pattern with a new observation (US-006 Sprint 7).

        Atomically loads existing patterns, updates the specified channel,
        and saves back to cache.

        Args:
            channel_id: YouTube channel ID (UCxxxx format).
            has_captions: Whether the checked video had captions.

        Returns:
            Updated ChannelCaptionPattern for the channel.

        Example:
            >>> cache = CaptionCache(config)
            >>> pattern = cache.update_channel_pattern("UCabc", has_captions=True)
            >>> print(f"Channel {pattern.channel_id}: {pattern.success_rate:.0%} success")
        """
        patterns = self.load_channel_patterns()

        if channel_id not in patterns:
            patterns[channel_id] = ChannelCaptionPattern(channel_id=channel_id)

        patterns[channel_id].update(has_captions)
        self.save_channel_patterns(patterns)

        return patterns[channel_id]

    def get_stats(self) -> Dict[str, Any]:
        """Get cache statistics.

        Returns:
            Dict with cache metrics.
        """
        base_stats = super().get_stats()

        # Add caption-specific stats
        total_segments = 0
        auto_generated_count = 0
        manual_count = 0

        for entry in self.get_all().values():
            try:
                cached = CachedCaption.from_dict(entry.data)
                total_segments += len(cached.segments)
                if cached.is_auto_generated:
                    auto_generated_count += 1
                else:
                    manual_count += 1
            except Exception:
                pass

        base_stats.update({
            'total_segments': total_segments,
            'auto_generated_entries': auto_generated_count,
            'manual_entries': manual_count,
            'max_age_days': self.max_age_days,
            'enabled': self.enabled,
        })

        return base_stats


class CaptionNormalizationError(CaptionError):
    """Raised when caption normalization fails."""

    def __init__(self, reason: str = ""):
        self.reason = reason
        message = "Caption normalization failed"
        if reason:
            message += f": {reason}"
        super().__init__(message)


@dataclass
class NormalizationConfig:
    """Configuration for caption timestamp normalization.

    Attributes:
        overlap_strategy: How to handle overlapping segments.
            - 'merge': Merge overlapping segments into one.
            - 'split': Split at the midpoint of overlap.
            - 'truncate': Truncate earlier segment's end to later's start.
        gap_strategy: How to handle gaps between segments.
            - 'extend': Extend previous segment's end to next segment's start.
            - 'placeholder': Insert empty placeholder segments.
            - 'ignore': Leave gaps as-is.
        max_gap_to_extend: Maximum gap size (seconds) to extend (larger gaps use placeholder).
        min_segment_duration: Minimum valid segment duration (seconds).
        validate_timestamps: Whether to validate and fix timestamps.
    """

    overlap_strategy: str = "truncate"
    gap_strategy: str = "ignore"
    max_gap_to_extend: float = 1.0
    min_segment_duration: float = 0.1
    validate_timestamps: bool = True


class CaptionNormalizer:
    """Normalizes YouTube caption timestamps for consistency.

    YouTube captions can have irregular timing:
    - Overlapping segments (two segments with overlapping time ranges)
    - Gaps between segments
    - Inconsistent timestamp formats (VTT, SRT, JSON3)
    - Invalid timestamps (negative, end < start)

    This class normalizes segments to a consistent format expected by
    the matching stage.

    Edge Case Behaviors (US-009 Sprint 6):
    -------------------------------------

    **Negative Start Times:**
        - start_time < 0 is clamped to 0
        - Example: start=-5, end=2 → start=0, end=2
        - If clamping creates duration < min_segment_duration, end is extended

    **Negative Duration (start > end):**
        - When start > end (inverted timestamps), end is extended
        - New end = start + min_segment_duration
        - Example: start=8, end=3 with min=0.5 → start=8, end=8.5
        - Original start time is preserved; only end is adjusted

    **Overlapping Segments (overlap_strategy):**
        - "truncate" (default): First segment's end truncated to second's start
        - "merge": Segments merged, text concatenated with space
          Example: (0-5 "First"), (3-8 "Second") → (0-8 "First Second")
        - "split": Split at midpoint of overlap region

    **Duplicate Segment Indices:**
        - All segments are re-indexed sequentially (0, 1, 2, ...)
        - Original indices are ignored
        - Example: indices [5, 5, 5] → [0, 1, 2]

    **Gap Handling (gap_strategy):**
        - "ignore" (default): Gaps left as-is
        - "extend": Small gaps (≤ max_gap_to_extend) filled by extending
          previous segment's end_time. Large gaps create placeholder segments.
        - "placeholder": Always insert empty placeholder segment in gaps
        - Placeholder segments have text="" and preserve gap timing
          Example: (0-5), (15-20) with max_gap=2 → (0-5), (5-15 placeholder), (15-20)

    **Empty/Whitespace Text:**
        - Segments with empty or whitespace-only text are filtered out
        - This is intentional filtering, not counted as parse errors

    **Partial Recovery (US-005):**
        - Malformed segments that throw exceptions are skipped
        - Normalization succeeds if > min_success_ratio segments parse
        - Default threshold: 50% must succeed
        - Filtered segments (empty text) don't count against threshold

    Usage:
        normalizer = CaptionNormalizer()
        normalized = normalizer.normalize(caption_result.segments, video_id="abc123")

        # With custom config:
        config = NormalizationConfig(overlap_strategy="merge", gap_strategy="extend")
        normalizer = CaptionNormalizer(config)
        normalized = normalizer.normalize(segments)

    Example:
        >>> segments = [
        ...     CaptionSegment(0, 0.0, 5.0, "First", "vid"),
        ...     CaptionSegment(1, 4.0, 8.0, "Second", "vid"),  # Overlaps with first
        ...     CaptionSegment(2, 10.0, 12.0, "Third", "vid"),  # Gap before this
        ... ]
        >>> normalizer = CaptionNormalizer()
        >>> normalized = normalizer.normalize(segments)
    """

    def __init__(self, config: Optional[NormalizationConfig] = None):
        """Initialize the normalizer.

        Args:
            config: Optional normalization configuration.
        """
        self.config = config or NormalizationConfig()

    def normalize(
        self,
        segments: List[CaptionSegment],
        video_id: str = "",
        min_success_ratio: float = 0.5
    ) -> tuple[List[CaptionSegment], int]:
        """Normalize a list of caption segments with partial recovery (US-005).

        Applies the following normalization steps:
        1. Validate and fix individual segment timestamps (with per-segment error handling)
        2. Sort segments by start time
        3. Handle overlapping segments (based on overlap_strategy)
        4. Handle gaps between segments (based on gap_strategy)
        5. Re-index segments sequentially

        Partial recovery (US-005): If a segment fails to parse due to unexpected
        errors, it is skipped rather than failing the entire normalization. The
        number of skipped segments is returned, and partial results are accepted
        if more than min_success_ratio (default 50%) of segments parse successfully.

        Args:
            segments: List of CaptionSegment to normalize.
            video_id: Video ID for source_file field in new segments.
            min_success_ratio: Minimum ratio of segments that must parse successfully
                for partial results to be accepted (default: 0.5 = 50%).

        Returns:
            Tuple of (normalized_segments, skipped_count). The skipped_count
            indicates how many segments were skipped due to parse errors.

        Raises:
            CaptionNormalizationError: If normalization fails catastrophically
                (less than min_success_ratio of segments parsed successfully).
        """
        if not segments:
            return ([], 0)

        original_count = len(segments)
        skipped_count = 0  # Segments skipped due to parse errors (exceptions)
        filtered_count = 0  # Segments intentionally filtered (invalid but not errors)
        logger.debug(f"Normalizing {original_count} caption segments for video {video_id}")

        # Step 1: Validate and fix individual timestamps with per-segment error handling
        validated_segments = []
        if self.config.validate_timestamps:
            for i, seg in enumerate(segments):
                try:
                    validated = self._validate_segment(seg, video_id)
                    if validated is not None:
                        validated_segments.append(validated)
                    else:
                        # Segment was intentionally filtered (e.g., empty text, invalid timing)
                        # This is expected behavior, not an error
                        filtered_count += 1
                except Exception as e:
                    # Unexpected error during validation - log and skip segment (US-005)
                    # This counts toward the skip threshold
                    skipped_count += 1
                    logger.warning(
                        f"Skipped malformed segment {i} for video {video_id}: {e}"
                    )
                    # Emit a CaptionParseWarning for tracking (non-fatal)
                    try:
                        warning = CaptionParseWarning(video_id, i, str(e))
                        logger.debug(f"CaptionParseWarning: {warning}")
                    except Exception:
                        pass  # Don't let warning emission cause failures
            segments = validated_segments
        else:
            segments = list(segments)

        # Check if too many segments had parse ERRORS (US-005)
        # Only count unexpected exceptions against the threshold, not intentional filters
        if skipped_count > 0 and original_count > 0:
            # Calculate what fraction of segments had actual errors
            error_ratio = skipped_count / original_count
            if error_ratio > (1.0 - min_success_ratio):
                logger.warning(
                    f"Too many parse errors: {skipped_count}/{original_count} segments "
                    f"({error_ratio:.1%}) had errors, threshold is {1.0 - min_success_ratio:.0%}"
                )
                raise CaptionNormalizationError(
                    f"Partial recovery failed: {error_ratio:.1%} of segments had parse errors "
                    f"(threshold: {1.0 - min_success_ratio:.0%})"
                )

        if not segments:
            logger.warning("All segments were invalid after validation")
            return ([], skipped_count)

        # Log skipped/filtered segments summary (US-005)
        if skipped_count > 0 or filtered_count > 0:
            logger.info(
                f"Partial recovery: {skipped_count} segments had errors, "
                f"{filtered_count} filtered, {len(segments)} usable for video {video_id}"
            )

        # Step 2: Sort by start time
        segments = sorted(segments, key=lambda s: s.start_time)

        # Step 3: Handle overlapping segments
        segments = self._handle_overlaps(segments, video_id)

        # Step 4: Handle gaps
        segments = self._handle_gaps(segments, video_id)

        # Step 5: Re-index
        segments = self._reindex(segments)

        logger.debug(f"Normalization complete: {len(segments)} segments, {skipped_count} skipped")
        return (segments, skipped_count)

    def _validate_segment(
        self,
        segment: CaptionSegment,
        video_id: str
    ) -> Optional[CaptionSegment]:
        """Validate and fix a single segment's timestamps.

        Validation rules:
        - start_time must be >= 0
        - end_time must be > start_time
        - Duration must be >= min_segment_duration

        Args:
            segment: Segment to validate.
            video_id: Video ID for logging.

        Returns:
            Fixed segment, or None if segment is invalid and unfixable.
        """
        start = segment.start_time
        end = segment.end_time

        # Fix negative start time
        if start < 0:
            logger.debug(f"Fixing negative start_time ({start}) in segment {segment.index}")
            start = 0.0

        # Fix negative end time
        if end < 0:
            logger.debug(f"Invalid negative end_time ({end}) in segment {segment.index}")
            return None

        # Fix end <= start
        if end <= start:
            # Try extending end by minimum duration
            new_end = start + self.config.min_segment_duration
            logger.debug(
                f"Fixing end <= start ({end} <= {start}) in segment {segment.index}, "
                f"extending to {new_end}"
            )
            end = new_end

        # Check minimum duration
        duration = end - start
        if duration < self.config.min_segment_duration:
            logger.debug(
                f"Segment {segment.index} duration ({duration}) below minimum "
                f"({self.config.min_segment_duration}), extending"
            )
            end = start + self.config.min_segment_duration

        # Skip empty text
        if not segment.text.strip():
            logger.debug(f"Skipping empty segment {segment.index}")
            return None

        return CaptionSegment(
            index=segment.index,
            start_time=start,
            end_time=end,
            text=segment.text,
            source_file=segment.source_file or video_id
        )

    def _handle_overlaps(
        self,
        segments: List[CaptionSegment],
        video_id: str
    ) -> List[CaptionSegment]:
        """Handle overlapping segments based on strategy.

        Args:
            segments: Sorted list of segments.
            video_id: Video ID for new segments.

        Returns:
            List of segments with overlaps resolved.
        """
        if len(segments) < 2:
            return segments

        strategy = self.config.overlap_strategy
        result = []

        i = 0
        while i < len(segments):
            current = segments[i]

            # Check for overlap with next segment
            if i + 1 < len(segments):
                next_seg = segments[i + 1]

                if current.end_time > next_seg.start_time:
                    # Overlap detected
                    logger.debug(
                        f"Overlap detected: segment {current.index} "
                        f"({current.start_time:.2f}-{current.end_time:.2f}) overlaps with "
                        f"segment {next_seg.index} ({next_seg.start_time:.2f}-{next_seg.end_time:.2f})"
                    )

                    if strategy == "merge":
                        # Merge overlapping segments
                        merged = self._merge_segments(current, next_seg, video_id)
                        # Replace next segment with merged for further processing
                        segments[i + 1] = merged
                        i += 1
                        continue

                    elif strategy == "split":
                        # Split at midpoint
                        midpoint = (current.end_time + next_seg.start_time) / 2
                        current = CaptionSegment(
                            index=current.index,
                            start_time=current.start_time,
                            end_time=midpoint,
                            text=current.text,
                            source_file=current.source_file or video_id
                        )
                        segments[i + 1] = CaptionSegment(
                            index=next_seg.index,
                            start_time=midpoint,
                            end_time=next_seg.end_time,
                            text=next_seg.text,
                            source_file=next_seg.source_file or video_id
                        )

                    elif strategy == "truncate":
                        # Truncate current's end to next's start
                        current = CaptionSegment(
                            index=current.index,
                            start_time=current.start_time,
                            end_time=next_seg.start_time,
                            text=current.text,
                            source_file=current.source_file or video_id
                        )

            result.append(current)
            i += 1

        return result

    def _merge_segments(
        self,
        seg1: CaptionSegment,
        seg2: CaptionSegment,
        video_id: str
    ) -> CaptionSegment:
        """Merge two overlapping segments into one.

        Args:
            seg1: First segment (earlier start time).
            seg2: Second segment (overlapping).
            video_id: Video ID for merged segment.

        Returns:
            Merged CaptionSegment.
        """
        return CaptionSegment(
            index=seg1.index,
            start_time=min(seg1.start_time, seg2.start_time),
            end_time=max(seg1.end_time, seg2.end_time),
            text=f"{seg1.text} {seg2.text}".strip(),
            source_file=seg1.source_file or seg2.source_file or video_id
        )

    def _handle_gaps(
        self,
        segments: List[CaptionSegment],
        video_id: str
    ) -> List[CaptionSegment]:
        """Handle gaps between segments based on strategy.

        Args:
            segments: List of segments with overlaps resolved.
            video_id: Video ID for new segments.

        Returns:
            List of segments with gaps handled.
        """
        if len(segments) < 2 or self.config.gap_strategy == "ignore":
            return segments

        strategy = self.config.gap_strategy
        result = []

        for i, segment in enumerate(segments):
            result.append(segment)

            # Check for gap before next segment
            if i + 1 < len(segments):
                next_seg = segments[i + 1]
                gap = next_seg.start_time - segment.end_time

                if gap > 0:
                    logger.debug(
                        f"Gap detected: {gap:.2f}s between segment {segment.index} "
                        f"and {next_seg.index}"
                    )

                    if strategy == "extend":
                        # Extend if gap is small enough
                        if gap <= self.config.max_gap_to_extend:
                            # Extend current segment's end
                            result[-1] = CaptionSegment(
                                index=segment.index,
                                start_time=segment.start_time,
                                end_time=next_seg.start_time,
                                text=segment.text,
                                source_file=segment.source_file or video_id
                            )
                        else:
                            # Insert placeholder for large gaps
                            placeholder = CaptionSegment(
                                index=-1,  # Will be re-indexed
                                start_time=segment.end_time,
                                end_time=next_seg.start_time,
                                text="",  # Empty placeholder
                                source_file=video_id
                            )
                            result.append(placeholder)

                    elif strategy == "placeholder":
                        # Always insert placeholder
                        placeholder = CaptionSegment(
                            index=-1,
                            start_time=segment.end_time,
                            end_time=next_seg.start_time,
                            text="",
                            source_file=video_id
                        )
                        result.append(placeholder)

        return result

    def _reindex(self, segments: List[CaptionSegment]) -> List[CaptionSegment]:
        """Re-index segments sequentially.

        Args:
            segments: List of segments to re-index.

        Returns:
            List of segments with sequential indexes starting from 0.
        """
        return [
            CaptionSegment(
                index=i,
                start_time=seg.start_time,
                end_time=seg.end_time,
                text=seg.text,
                source_file=seg.source_file
            )
            for i, seg in enumerate(segments)
        ]

    def validate_continuity(
        self,
        segments: List[CaptionSegment]
    ) -> List[str]:
        """Validate segment timing continuity.

        Checks for common issues:
        - Negative durations
        - end_time < start_time
        - Overlaps
        - Gaps

        Args:
            segments: List of segments to validate.

        Returns:
            List of warning messages (empty if all valid).
        """
        warnings = []

        for i, seg in enumerate(segments):
            # Check individual segment
            if seg.end_time < seg.start_time:
                warnings.append(
                    f"Segment {i}: end_time ({seg.end_time}) < start_time ({seg.start_time})"
                )

            duration = seg.end_time - seg.start_time
            if duration <= 0:
                warnings.append(f"Segment {i}: non-positive duration ({duration})")

            # Check relationship with next segment
            if i + 1 < len(segments):
                next_seg = segments[i + 1]

                if seg.end_time > next_seg.start_time:
                    overlap = seg.end_time - next_seg.start_time
                    warnings.append(
                        f"Segments {i}-{i+1}: overlap of {overlap:.2f}s"
                    )

        return warnings

    @staticmethod
    def convert_timestamp_to_seconds(timestamp: str) -> Optional[float]:
        """Convert a timestamp string to seconds.

        Supports formats:
        - HH:MM:SS,mmm (SRT)
        - HH:MM:SS.mmm (VTT)
        - MM:SS.mmm (VTT short)
        - Seconds as float string

        Args:
            timestamp: Timestamp string to convert.

        Returns:
            Time in seconds, or None if parsing fails.
        """
        if not timestamp:
            return None

        timestamp = timestamp.strip().replace(',', '.')

        # Try float directly (e.g., "1.5")
        try:
            return float(timestamp)
        except ValueError:
            pass

        # Pattern for HH:MM:SS.mmm or MM:SS.mmm
        match = re.match(r'^(?:(\d+):)?(\d+):(\d+)(?:\.(\d+))?$', timestamp)
        if match:
            hours = int(match.group(1)) if match.group(1) else 0
            minutes = int(match.group(2))
            seconds = int(match.group(3))
            millis = int(match.group(4).ljust(3, '0')[:3]) if match.group(4) else 0

            return hours * 3600 + minutes * 60 + seconds + millis / 1000.0

        logger.warning(f"Could not parse timestamp: {timestamp}")
        return None

    @staticmethod
    def seconds_to_vtt_timestamp(seconds: float) -> str:
        """Convert seconds to VTT timestamp format.

        Args:
            seconds: Time in seconds.

        Returns:
            VTT timestamp string (HH:MM:SS.mmm).
        """
        if seconds < 0:
            seconds = 0

        hours = int(seconds // 3600)
        minutes = int((seconds % 3600) // 60)
        secs = int(seconds % 60)
        millis = int((seconds * 1000) % 1000)

        return f"{hours:02d}:{minutes:02d}:{secs:02d}.{millis:03d}"

    @staticmethod
    def seconds_to_srt_timestamp(seconds: float) -> str:
        """Convert seconds to SRT timestamp format.

        Args:
            seconds: Time in seconds.

        Returns:
            SRT timestamp string (HH:MM:SS,mmm).
        """
        vtt_ts = CaptionNormalizer.seconds_to_vtt_timestamp(seconds)
        return vtt_ts.replace('.', ',')


