    def _get_retry_budget(self, category: CaptionErrorCategory) -> int:
        """Get the retry budget for a specific error category (US-003 Sprint 7).

        Looks up the category-specific retry budget from config, falling back
        to DEFAULT_RETRY_BUDGETS if not configured.

        Args:
            category: The CaptionErrorCategory enum value.

        Returns:
            Maximum retry attempts for this category.
        """
        # Check config for category-specific budgets
        if self.config:
            caption_config = getattr(self.config.download, 'caption_first', None)
            if caption_config:
                retry_budgets = getattr(caption_config, 'retry_budgets', None)
                if retry_budgets:
                    # Config uses lowercase category names
                    category_key = category.name.lower()
                    if category_key in retry_budgets:
                        return retry_budgets[category_key]

        # Fall back to default budgets
        return DEFAULT_RETRY_BUDGETS.get(category, 0)

    def _with_retry(
        self,
        func,
        video_id: str,
        operation: str,
        max_retries: int,
        retry_delay: float,
        metrics: Optional['CaptionMetrics'] = None
    ):
        """Execute a function with category-aware retry logic (US-003 Sprint 7).

        Implements retry logic that categorizes errors and applies type-specific
        retry budgets. Different error types have different retry strategies:
        - NETWORK errors retry aggressively (budget: 3)
        - TIMEOUT errors get moderate retries (budget: 2)
        - PARSE errors rarely succeed on retry (budget: 1)
        - UNAVAILABLE never retries (budget: 0)
        - RATE_LIMIT retries with longer backoff (budget: 2)

        Updated in US-003 Sprint 7 to use CaptionErrorCategory for smarter retries.

        Backoff formula: delay * (2 ^ attempt)
        Example with delay=2.0: 2s, 4s, 8s, 16s...

        Args:
            func: Callable to execute (no arguments).
            video_id: Video ID for logging context.
            operation: Operation name for logging (e.g., "fetch_captions").
            max_retries: Maximum retry attempts (overridden by category budget).
            retry_delay: Base delay for exponential backoff (seconds).
            metrics: Optional CaptionMetrics for error category tracking.

        Returns:
            Result from func.

        Raises:
            CaptionUnavailableError: If captions don't exist (NOT retried).
            CaptionFetchError: If all retries exhausted on temporary errors.
        """
        last_error = None
        attempt = 0
        # Track attempts per category to respect category-specific budgets
        category_attempts: Dict[CaptionErrorCategory, int] = {}

        while True:
            try:
                result = func()
                if attempt > 0:
                    logger.info(
                        f"Caption {operation} succeeded on attempt {attempt + 1} "
                        f"for video {video_id}"
                    )
                return result

            except CaptionUnavailableError as e:
                # Categorize and log (always UNAVAILABLE category)
                category = CaptionErrorCategory.UNAVAILABLE
                if metrics:
                    metrics.record_error_category(category, video_id)

                logger.debug(
                    f"Caption {operation} failed for video {video_id}: "
                    f"{category.name} error, no retry (budget: 0)"
                )
                raise

            except CaptionFetchError as e:
                # Categorize the error
                category = categorize_caption_error(e, e.reason)
                if metrics:
                    metrics.record_error_category(category, video_id)

                # Get category-specific retry budget
                budget = self._get_retry_budget(category)
                category_attempts[category] = category_attempts.get(category, 0) + 1
                attempts_for_category = category_attempts[category]

                last_error = e

                # Check if we've exhausted the budget for this category
                if attempts_for_category > budget:
                    logger.warning(
                        f"Caption {operation} failed for video {video_id}: "
                        f"{category.name} error, no retry (attempt {attempts_for_category}/{budget})"
                    )
                    break  # Exit loop, raise last error

                # Retry is allowed for this category
                wait_time = retry_delay * (2 ** attempt)

                # RATE_LIMIT gets longer backoff
                if category == CaptionErrorCategory.RATE_LIMIT:
                    wait_time *= 2  # Double the backoff for rate limits

                logger.warning(
                    f"Caption {operation} failed for video {video_id}: "
                    f"{category.name} error, retry {attempts_for_category}/{budget}. "
                    f"Waiting {wait_time:.1f}s..."
                )
                time.sleep(wait_time)
                attempt += 1

                # Safety check: respect overall max_retries as a backstop
                if attempt > max_retries:
                    logger.error(
                        f"Caption {operation} failed for video {video_id}: "
                        f"exceeded max retries ({max_retries})"
                    )
                    break

            except Exception as e:
                # Categorize unexpected errors
                category = categorize_caption_error(e, str(e))
                if metrics:
                    metrics.record_error_category(category, video_id)

                # Get category-specific retry budget
                budget = self._get_retry_budget(category)
                category_attempts[category] = category_attempts.get(category, 0) + 1
                attempts_for_category = category_attempts[category]

                last_error = CaptionFetchError(video_id, str(e))

                # Check if we've exhausted the budget for this category
                if attempts_for_category > budget:
                    logger.warning(
                        f"Caption {operation} failed for video {video_id}: "
                        f"{category.name} error ({type(e).__name__}), no retry "
                        f"(attempt {attempts_for_category}/{budget})"
                    )
                    break

                wait_time = retry_delay * (2 ** attempt)
                logger.warning(
                    f"Caption {operation} failed for video {video_id}: "
                    f"{category.name} error ({type(e).__name__}), "
                    f"retry {attempts_for_category}/{budget}. "
                    f"Waiting {wait_time:.1f}s..."
                )
                time.sleep(wait_time)
                attempt += 1

                # Safety check: respect overall max_retries as a backstop
                if attempt > max_retries:
                    logger.error(
                        f"Caption {operation} failed for video {video_id}: "
                        f"exceeded max retries ({max_retries})"
                    )
                    break

        # All retries exhausted
        raise last_error

    def _sort_videos_by_channel_success(
        self,
        video_ids: List[str],
        channel_patterns: Dict[str, 'ChannelCaptionPattern']
    ) -> List[str]:
        """Sort videos by channel caption availability success rate (US-009 Sprint 7).

        Reorders videos so that those from channels with higher caption availability
        are fetched first. This improves average success rate early in the batch
        and helps identify problematic channels faster.

        Args:
            video_ids: List of YouTube video IDs to sort.
            channel_patterns: Dict mapping channel_id -> ChannelCaptionPattern.

        Returns:
            Sorted list of video IDs, with high-success channels first.
            Videos from unknown channels are placed at the end.

        Example:
            >>> patterns = {
            ...     'UCabc': ChannelCaptionPattern('UCabc', 10, 10, 1.0),  # 100% success
            ...     'UCdef': ChannelCaptionPattern('UCdef', 10, 5, 0.5),   # 50% success
            ... }
            >>> sorted_vids = fetcher._sort_videos_by_channel_success(
            ...     ['vid1_UCdef', 'vid2_UCabc', 'vid3_unknown'],
            ...     patterns
            ... )
            >>> # vid2_UCabc comes first (100%), then vid1_UCdef (50%), then unknown
        """
        if not channel_patterns:
            return video_ids

        def get_channel_success_rate(video_id: str) -> float:
            """Get success rate for video's channel, or 0.5 for unknown."""
            # Try to extract channel ID from video metadata
            channel_id = self._get_channel_id_from_video(video_id)
            if channel_id and channel_id in channel_patterns:
                pattern = channel_patterns[channel_id]
                if pattern.videos_checked > 0:
                    return pattern.success_rate
            # Unknown channel: use neutral 0.5 (middle of the pack)
            return 0.5

        # Sort descending by success rate (highest first)
        sorted_videos = sorted(
            video_ids,
            key=lambda vid: get_channel_success_rate(vid),
            reverse=True
        )

        return sorted_videos

    def _get_channel_id_from_video(self, video_id: str) -> Optional[str]:
        """Extract channel ID for a video (US-009 Sprint 7).

        Uses cached metadata if available, otherwise returns None.

        Args:
            video_id: YouTube video ID.

        Returns:
            Channel ID (UCxxxx format) if known, None otherwise.
        """
        # Check if we have cached metadata with channel info
        # This would be populated during batch_precheck_by_channel or other metadata fetch
        if hasattr(self, '_video_channel_map'):
            return self._video_channel_map.get(video_id)
        return None

    def set_video_channel_map(self, video_channel_map: Dict[str, str]) -> None:
        """Set video-to-channel mapping for fetch prioritization (US-009 Sprint 7).

        Called before fetch_captions_batch() to enable channel-based sorting.

        Args:
            video_channel_map: Dict mapping video_id -> channel_id.

        Example:
            >>> fetcher.set_video_channel_map({
            ...     'dQw4w9WgXcQ': 'UCuAXFkgsw1L7xaCfnd5JJOw',
            ...     'abc123XYZ01': 'UCabc123def456',
            ... })
        """
        self._video_channel_map = dict(video_channel_map)
        logger.debug(f"Video-channel map set: {len(video_channel_map)} videos")

    def fetch_captions_batch(
        self,
        video_ids: List[str],
        preferred_language: Optional[str] = None,
        max_workers: Optional[int] = None,
        metrics: Optional['CaptionMetrics'] = None,
        progress_callback: Optional[Callable[[str, str, Dict[str, Any]], None]] = None,
        skip_video_ids: Optional[set] = None,
        batch_checkpoint: Optional['CaptionBatchCheckpoint'] = None,
        checkpoint_save_interval: int = 10,
    ) -> Dict[str, Union[CaptionResult, Dict[str, Any]]]:
        """Fetch captions for multiple videos in parallel using ThreadPoolExecutor.

        Implements US-001: Parallel caption fetching for faster processing of
        projects with 50+ videos. Uses ThreadPoolExecutor with configurable
        max_workers (default: 4).

        US-007 Sprint 7: Adds error pattern detection to identify systemic issues
        (geoblocking, rate limiting) early in the batch. When 30%+ of the first
        N videos fail with the same error, the pattern is detected and handled
        based on config.abort_on_error_pattern setting:
        - 'abort': Raises ErrorPatternAbortError with partial results
        - 'warn': Logs warning and continues fetching (default)
        - 'skip': Disables pattern detection entirely

        US-005 Sprint 8: Adds checkpoint support for partial result recovery.
        When batch_checkpoint is provided:
        - Saves checkpoint every checkpoint_save_interval successful fetches
        - On ErrorPatternAbortError, saves checkpoint with abort info
        - Enables resume by skipping already-fetched videos in checkpoint

        Args:
            video_ids: List of YouTube video IDs to fetch captions for.
            preferred_language: Preferred caption language (ISO 639-1 code).
                If None, uses config setting.
            max_workers: Number of parallel workers. If None, uses config setting
                (caption_first.max_parallel_fetches, default: 4).
            metrics: Optional CaptionMetrics instance for thread-safe tracking.
                If provided, metrics are updated as fetches complete.
            progress_callback: Optional callback for real-time progress updates.
                Called with (video_id, status, details) where:
                - status: 'fetching', 'success', 'failed', 'skipped', 'pattern_detected'
                - details: Dict with language, quality, segment_count, error, etc.
            skip_video_ids: Set of video IDs to skip (already cached).
            batch_checkpoint: Optional CaptionBatchCheckpoint for partial result recovery.
                If provided, results are saved periodically and on abort.
            checkpoint_save_interval: Save checkpoint every N successful fetches.
                Default: 10. Only used if batch_checkpoint is provided.

        Returns:
            Dict mapping video_id to either:
            - CaptionResult on success
            - Dict with 'error': True or 'unavailable': True on failure

        Raises:
            ErrorPatternAbortError: When abort_on_error_pattern='abort' and
                error pattern is detected. Exception contains partial_results.
                If batch_checkpoint is provided, checkpoint is saved before raising.

        Example:
            fetcher = CaptionFetcher(config)
            metrics = CaptionMetrics()

            # With checkpointing (US-005 Sprint 8)
            checkpoint = CaptionBatchCheckpoint(
                total_requested=len(video_ids),
                remaining_video_ids=list(video_ids)
            )
            checkpoint_path = CaptionBatchCheckpoint.get_checkpoint_path(project_dir)

            try:
                results = fetcher.fetch_captions_batch(
                    video_ids=['abc123XYZ01', 'def456ABC02', ...],
                    metrics=metrics,
                    batch_checkpoint=checkpoint,
                    checkpoint_save_interval=10,
                )
            except ErrorPatternAbortError:
                # Checkpoint already saved with abort info
                checkpoint.save(checkpoint_path)
        """
        if not video_ids:
            return {}

        # Get max_workers from config or parameter
        workers = max_workers
        caption_config = None
        if workers is None:
            if self.config:
                caption_config = getattr(self.config.download, 'caption_first', None)
                if caption_config:
                    workers = getattr(caption_config, 'max_parallel_fetches', 4)
            if workers is None:
                workers = 4

        # Ensure at least 1 worker
        workers = max(1, workers)

        # US-007 Sprint 7: Setup error pattern detection
        error_pattern_mode = "warn"  # Default
        error_pattern_threshold = 0.3  # Default 30%
        error_pattern_sample_size = 10  # Default first 10 videos
        if caption_config is None and self.config:
            caption_config = getattr(self.config.download, 'caption_first', None)
        if caption_config:
            error_pattern_mode = getattr(caption_config, 'abort_on_error_pattern', 'warn')
            error_pattern_threshold = getattr(caption_config, 'error_pattern_threshold', 0.3)
            error_pattern_sample_size = getattr(caption_config, 'error_pattern_sample_size', 10)

        # Create error pattern detector (None if mode is 'skip')
        pattern_detector: Optional[ErrorPatternDetector] = None
        if error_pattern_mode != 'skip':
            pattern_detector = ErrorPatternDetector(
                threshold=error_pattern_threshold,
                sample_size=error_pattern_sample_size
            )

        # Filter out skipped video IDs
        skip_set = skip_video_ids or set()
        videos_to_fetch = [vid for vid in video_ids if vid not in skip_set]

        # US-009 Sprint 7: Prioritize fetch order by channel success rate
        prioritize_by_channel = True  # Default
        if caption_config:
            prioritize_by_channel = getattr(caption_config, 'prioritize_by_channel', True)

        if prioritize_by_channel and metrics and metrics.channel_patterns:
            videos_to_fetch = self._sort_videos_by_channel_success(
                videos_to_fetch, metrics.channel_patterns
            )
            logger.info(
                f"Prioritized fetch order by channel success rate "
                f"({len(metrics.channel_patterns)} channels)"
            )

        logger.info(
            f"Batch caption fetch: {len(videos_to_fetch)} videos with {workers} workers "
            f"({len(skip_set)} skipped)"
        )

        results: Dict[str, Union[CaptionResult, Dict[str, Any]]] = {}
        total_videos = len(videos_to_fetch)

        # US-005 Sprint 8: Track checkpoint save state
        checkpoint_success_count = 0
        checkpoint_lock = threading.Lock()

        # US-002 Sprint 6: Get timeout threshold for slow fetch warning
        timeout_threshold = self._timeout if self._timeout else 30.0
        slow_threshold = timeout_threshold * 0.8  # 80% of timeout

        # US-008 Sprint 8: Worker progress tracking with ETA calculation
        stuck_threshold = 60.0  # Default
        if caption_config:
            stuck_threshold = getattr(caption_config, 'stuck_worker_threshold', 60.0)
        worker_tracker = WorkerProgressTracker(
            total_videos=total_videos,
            stuck_threshold_seconds=stuck_threshold,
            max_fetch_times=10,  # Rolling average window
        )
        worker_tracker.initialize_workers(workers)

        # Map thread ident to worker_id for tracking
        thread_to_worker: Dict[int, int] = {}
        thread_lock = threading.Lock()
        next_worker_id = [0]  # Mutable container for closure

        def get_worker_id() -> int:
            """Get or assign worker_id for current thread."""
            thread_id = threading.get_ident()
            with thread_lock:
                if thread_id not in thread_to_worker:
                    thread_to_worker[thread_id] = next_worker_id[0]
                    next_worker_id[0] += 1
                return thread_to_worker[thread_id]

        def fetch_single(video_id: str, index: int) -> tuple:
            """Fetch captions for a single video (runs in thread).

            US-002 Sprint 6: Tracks start_time and elapsed_seconds for each video.
            Adds elapsed_seconds to progress_callback details dict.
            Logs warning if video takes >80% of timeout threshold.
            US-008 Sprint 8: Tracks worker progress and includes worker stats in callback.
            """
            import time
            start_time = time.perf_counter()

            # US-008 Sprint 8: Track worker start
            worker_id = get_worker_id()
            worker_tracker.worker_start(worker_id, video_id)

            # Notify progress callback: fetching (with worker stats)
            if progress_callback:
                try:
                    worker_stats = worker_tracker.get_worker_stats()
                    progress_callback(video_id, 'fetching', {
                        'index': index + 1,
                        'total': total_videos,
                        'worker_id': worker_id,
                        'worker_stats': worker_stats,
                    })
                except Exception as e:
                    logger.debug(f"Progress callback error: {e}")

            # Record fetch attempt in metrics (thread-safe)
            if metrics:
                metrics.record_fetch_attempt(video_id)

            try:
                result = self.fetch_captions_auto_language_with_retry(
                    video_id,
                    preferred_language=preferred_language
                )

                # US-002 Sprint 6: Calculate elapsed time
                elapsed_seconds = time.perf_counter() - start_time

                # US-002 Sprint 6: Warn if video took >80% of timeout
                if elapsed_seconds > slow_threshold:
                    logger.warning(
                        f"Slow caption fetch for {video_id}: {elapsed_seconds:.1f}s "
                        f"(>{slow_threshold:.1f}s threshold, {int(elapsed_seconds/timeout_threshold*100)}% of timeout)"
                    )

                # Record success in metrics (thread-safe)
                if metrics:
                    metrics.record_fetch_success(
                        video_id=video_id,
                        language=result.language,
                        quality=result.caption_quality,
                        segment_count=len(result.segments),
                        is_auto_generated=result.is_auto_generated,
                        elapsed_seconds=elapsed_seconds,  # US-002 Sprint 6
                        format_source=result.format_source,  # US-004 Sprint 6
                        preferred_format=self._preferred_formats[0] if self._preferred_formats else None  # US-004 Sprint 6
                    )

                # US-008 Sprint 8: Mark worker complete
                worker_tracker.worker_complete(worker_id)

                # Notify progress callback: success (with worker stats)
                if progress_callback:
                    try:
                        worker_stats = worker_tracker.get_worker_stats()
                        progress_callback(video_id, 'success', {
                            'index': index + 1,
                            'total': total_videos,
                            'language': result.language,
                            'quality': result.caption_quality,
                            'segment_count': len(result.segments),
                            'is_auto_generated': result.is_auto_generated,
                            'elapsed_seconds': elapsed_seconds,  # US-002 Sprint 6
                            'format_source': result.format_source,  # US-004 Sprint 6
                            'worker_id': worker_id,  # US-008 Sprint 8
                            'worker_stats': worker_stats,  # US-008 Sprint 8
                        })
                    except Exception as e:
                        logger.debug(f"Progress callback error: {e}")

                return video_id, result

            except CaptionUnavailableError as e:
                # US-002 Sprint 6: Calculate elapsed time even for failures
                elapsed_seconds = time.perf_counter() - start_time

                # US-008 Sprint 8: Mark worker complete (even on failure)
                worker_tracker.worker_complete(worker_id)

                error_result = {
                    'video_id': video_id,
                    'unavailable': True,
                    'reason': str(e.reason),
                    'caption_quality': 'low',
                    'elapsed_seconds': elapsed_seconds,  # US-002 Sprint 6
                }

                # Record failure in metrics (thread-safe)
                if metrics:
                    metrics.record_fetch_failure(
                        video_id=video_id,
                        reason='unavailable',
                        elapsed_seconds=elapsed_seconds  # US-002 Sprint 6
                    )

                # Notify progress callback: failed (with worker stats)
                if progress_callback:
                    try:
                        worker_stats = worker_tracker.get_worker_stats()
                        progress_callback(video_id, 'failed', {
                            'index': index + 1,
                            'total': total_videos,
                            'reason': 'unavailable',
                            'error': str(e.reason),
                            'elapsed_seconds': elapsed_seconds,  # US-002 Sprint 6
                            'worker_id': worker_id,  # US-008 Sprint 8
                            'worker_stats': worker_stats,  # US-008 Sprint 8
                        })
                    except Exception as cb_err:
                        logger.debug(f"Progress callback error: {cb_err}")

                return video_id, error_result

            except CaptionFetchError as e:
                # US-002 Sprint 6: Calculate elapsed time even for failures
                elapsed_seconds = time.perf_counter() - start_time

                # US-008 Sprint 8: Mark worker complete (even on failure)
                worker_tracker.worker_complete(worker_id)

                error_result = {
                    'video_id': video_id,
                    'error': True,
                    'reason': str(e.reason),
                    'caption_quality': 'low',
                    'elapsed_seconds': elapsed_seconds,  # US-002 Sprint 6
                }

                # Record failure in metrics (thread-safe)
                if metrics:
                    metrics.record_fetch_failure(
                        video_id=video_id,
                        reason='error',
                        elapsed_seconds=elapsed_seconds  # US-002 Sprint 6
                    )

                # Notify progress callback: failed (with worker stats)
                if progress_callback:
                    try:
                        worker_stats = worker_tracker.get_worker_stats()
                        progress_callback(video_id, 'failed', {
                            'index': index + 1,
                            'total': total_videos,
                            'reason': 'error',
                            'error': str(e.reason),
                            'elapsed_seconds': elapsed_seconds,  # US-002 Sprint 6
                            'worker_id': worker_id,  # US-008 Sprint 8
                            'worker_stats': worker_stats,  # US-008 Sprint 8
                        })
                    except Exception as cb_err:
                        logger.debug(f"Progress callback error: {cb_err}")

                return video_id, error_result

            except Exception as e:
                # US-002 Sprint 6: Calculate elapsed time even for failures
                elapsed_seconds = time.perf_counter() - start_time

                # US-008 Sprint 8: Mark worker complete (even on failure)
                worker_tracker.worker_complete(worker_id)

                # Unexpected error
                error_result = {
                    'video_id': video_id,
                    'error': True,
                    'reason': str(e),
                    'caption_quality': 'low',
                    'elapsed_seconds': elapsed_seconds,  # US-002 Sprint 6
                }

                # Record failure in metrics (thread-safe)
                if metrics:
                    metrics.record_fetch_failure(
                        video_id=video_id,
                        reason='error',
                        elapsed_seconds=elapsed_seconds  # US-002 Sprint 6
                    )

                logger.exception(f"Unexpected error fetching captions for {video_id}")

                # Notify progress callback: failed (with worker stats)
                if progress_callback:
                    try:
                        worker_stats = worker_tracker.get_worker_stats()
                        progress_callback(video_id, 'failed', {
                            'index': index + 1,
                            'total': total_videos,
                            'reason': 'error',
                            'error': str(e),
                            'elapsed_seconds': elapsed_seconds,  # US-002 Sprint 6
                            'worker_id': worker_id,  # US-008 Sprint 8
                            'worker_stats': worker_stats,  # US-008 Sprint 8
                        })
                    except Exception as cb_err:
                        logger.debug(f"Progress callback error: {cb_err}")

                return video_id, error_result

        # US-007 Sprint 7: Track whether we've handled a pattern already
        pattern_handled = False

        # Execute fetches in parallel
        with ThreadPoolExecutor(max_workers=workers) as executor:
            futures = {
                executor.submit(fetch_single, video_id, idx): video_id
                for idx, video_id in enumerate(videos_to_fetch)
            }

            for future in as_completed(futures):
                video_id = futures[future]
                try:
                    vid, result = future.result()
                    results[vid] = result

                    # US-005 Sprint 8: Update checkpoint and save periodically
                    if batch_checkpoint is not None:
                        with checkpoint_lock:
                            batch_checkpoint.update(vid, result)
                            # Save checkpoint every N successful fetches
                            if isinstance(result, CaptionResult):
                                checkpoint_success_count += 1
                                if checkpoint_success_count % checkpoint_save_interval == 0:
                                    # Note: save path must be provided by caller
                                    logger.debug(
                                        f"Checkpoint: {checkpoint_success_count} successes "
                                        f"({len(batch_checkpoint.results)}/{total_videos} processed)"
                                    )

                    # US-007 Sprint 7: Record result with pattern detector
                    if pattern_detector and not pattern_handled:
                        if isinstance(result, CaptionResult):
                            pattern_detector.record_success(vid)
                        else:
                            # It's an error dict
                            error_reason = result.get('reason', 'unknown error')
                            pattern_detector.record_error(vid, error_reason)

                        # Check if we should evaluate patterns
                        if pattern_detector.should_check_pattern():
                            pattern_result = pattern_detector.check_pattern()

                            if pattern_result.detected:
                                # Log the pattern with full details
                                logger.warning(
                                    f"Error pattern detected: {pattern_result.error_signature} "
                                    f"({len(pattern_result.affected_video_ids)}/{pattern_result.sample_size} videos, "
                                    f"{pattern_result.ratio * 100:.1f}%) - {pattern_result.likely_cause}"
                                )

                                # Record in metrics if available
                                if metrics:
                                    metrics.record_error_pattern_detected(
                                        pattern_result.error_signature,
                                        len(pattern_result.affected_video_ids),
                                        pattern_result.sample_size
                                    )

                                # Notify progress callback about pattern
                                if progress_callback:
                                    try:
                                        progress_callback('', 'pattern_detected', {
                                            'error_signature': pattern_result.error_signature,
                                            'affected_count': len(pattern_result.affected_video_ids),
                                            'sample_size': pattern_result.sample_size,
                                            'ratio': pattern_result.ratio,
                                            'likely_cause': pattern_result.likely_cause,
                                        })
                                    except Exception as cb_err:
                                        logger.debug(f"Progress callback error: {cb_err}")

                                # Handle based on mode
                                if error_pattern_mode == 'abort':
                                    logger.error(
                                        f"Aborting batch fetch due to error pattern: "
                                        f"{pattern_result}"
                                    )
                                    # Cancel remaining futures
                                    for f in futures:
                                        f.cancel()

                                    # US-005 Sprint 8: Save checkpoint before abort
                                    if batch_checkpoint is not None:
                                        # Calculate remaining video IDs
                                        processed_ids = set(results.keys())
                                        remaining_ids = [
                                            vid for vid in videos_to_fetch
                                            if vid not in processed_ids
                                        ]
                                        batch_checkpoint.mark_aborted(
                                            reason=str(pattern_result),
                                            pattern_result=pattern_result,
                                            remaining_ids=remaining_ids
                                        )
                                        logger.info(
                                            f"Checkpoint saved before abort: "
                                            f"{batch_checkpoint.success_count} successes, "
                                            f"{len(remaining_ids)} remaining"
                                        )

                                    raise ErrorPatternAbortError(
                                        pattern_result=pattern_result,
                                        partial_results=dict(results)
                                    )
                                # 'warn' mode: already logged, continue

                            pattern_handled = True  # Only check once

                except Exception as e:
                    if isinstance(e, ErrorPatternAbortError):
                        raise  # Re-raise abort exception
                    # Should not happen as fetch_single catches all exceptions
                    logger.error(f"Batch fetch future error for {video_id}: {e}")
                    results[video_id] = {
                        'video_id': video_id,
                        'error': True,
                        'reason': str(e),
                        'caption_quality': 'low',
                    }

                    # Also record this with pattern detector
                    if pattern_detector and not pattern_handled:
                        pattern_detector.record_error(video_id, str(e))

        logger.info(
            f"Batch caption fetch complete: {len(results)} processed, "
            f"{sum(1 for r in results.values() if isinstance(r, CaptionResult))} succeeded"
        )

        return results

    def resume_from_checkpoint(
        self,
        checkpoint: 'CaptionBatchCheckpoint',
        video_ids: List[str],
        preferred_language: Optional[str] = None,
        max_workers: Optional[int] = None,
        metrics: Optional['CaptionMetrics'] = None,
        progress_callback: Optional[Callable[[str, str, Dict[str, Any]], None]] = None,
        checkpoint_save_interval: int = 10,
    ) -> Dict[str, Union[CaptionResult, Dict[str, Any]]]:
        """Resume batch caption fetch from a checkpoint (US-005 Sprint 8).

        Loads partial results from checkpoint, skips already-fetched videos,
        and continues fetching remaining videos. Merges checkpoint results
        with new fetch results.

        Args:
            checkpoint: CaptionBatchCheckpoint with partial results.
            video_ids: Complete list of video IDs for the batch (same as original).
            preferred_language: Preferred caption language (ISO 639-1 code).
            max_workers: Number of parallel workers.
            metrics: Optional CaptionMetrics instance.
            progress_callback: Optional progress callback.
            checkpoint_save_interval: Save checkpoint every N successful fetches.

        Returns:
            Combined dict of checkpoint results + new fetch results.

        Example:
            checkpoint_path = CaptionBatchCheckpoint.get_checkpoint_path(project_dir)
            checkpoint = CaptionBatchCheckpoint.load(checkpoint_path)

            if checkpoint and checkpoint.aborted:
                print(f"Resuming from {checkpoint.success_count} successful fetches")
                results = fetcher.resume_from_checkpoint(
                    checkpoint=checkpoint,
                    video_ids=all_video_ids,
                )
        """
        # Start with existing results from checkpoint
        results = dict(checkpoint.results)

        # Determine which videos still need fetching
        skip_video_ids = set(checkpoint.results.keys())
        remaining_ids = [vid for vid in video_ids if vid not in skip_video_ids]

        if not remaining_ids:
            logger.info("Resume: All videos already fetched in checkpoint")
            return results

        logger.info(
            f"Resuming batch fetch: {len(remaining_ids)} remaining "
            f"(skipping {len(skip_video_ids)} from checkpoint)"
        )

        # Clear abort state since we're resuming
        checkpoint.aborted = False
        checkpoint.abort_reason = ""
        checkpoint.abort_pattern_info = None
        checkpoint.remaining_video_ids = remaining_ids

        # Fetch remaining videos (checkpoint will be updated internally)
        new_results = self.fetch_captions_batch(
            video_ids=remaining_ids,
            preferred_language=preferred_language,
            max_workers=max_workers,
            metrics=metrics,
            progress_callback=progress_callback,
            skip_video_ids=set(),  # We already filtered
            batch_checkpoint=checkpoint,
            checkpoint_save_interval=checkpoint_save_interval,
        )

        # Merge new results
        results.update(new_results)

        return results

    def fetch_captions(
        self,
        video_id: str,
        language: str = "en",
        prefer_manual: bool = True
    ) -> CaptionResult:
        """Fetch captions for a YouTube video.

        Args:
            video_id: YouTube video ID (11 characters).
            language: Preferred language code (ISO 639-1).
            prefer_manual: If True, prefer manually uploaded captions over auto-generated.

        Returns:
            CaptionResult with parsed segments and metadata.

        Raises:
            CaptionUnavailableError: If no captions exist for the video.
            CaptionFetchError: If fetch fails due to network/temporary error.
        """
        # Validate video ID format
        if not self._is_valid_video_id(video_id):
            raise CaptionFetchError(video_id, f"Invalid video ID format: {video_id}")

        video_url = f"https://www.youtube.com/watch?v={video_id}"

        # Create temp directory for subtitle files
        with tempfile.TemporaryDirectory() as temp_dir:
            temp_path = Path(temp_dir)

            # Determine which subtitle to fetch
            # Try manual captions first if preferred, then auto-generated
            formats_to_try = []
            if prefer_manual:
                formats_to_try.append((language, False))  # Manual
                formats_to_try.append((language, True))   # Auto
            else:
                formats_to_try.append((language, True))   # Auto
                formats_to_try.append((language, False))  # Manual

            # Also try English as fallback if not already preferred
            if language != "en":
                formats_to_try.append(("en", False))
                formats_to_try.append(("en", True))

            result = None
            last_error = None

            for lang, auto in formats_to_try:
                try:
                    result = self._fetch_subtitle(
                        video_url, video_id, temp_path, lang, auto
                    )
                    if result and result.segments:
                        return result
                except CaptionUnavailableError:
                    continue  # Try next format
                except CaptionFetchError as e:
                    last_error = e
                    continue

            # No captions found in any format
            if last_error:
                raise last_error
            raise CaptionUnavailableError(
                video_id,
                f"No captions available in {language} or en"
            )

    def _fetch_subtitle(
        self,
        video_url: str,
        video_id: str,
        temp_dir: Path,
        language: str,
        auto_generated: bool
    ) -> Optional[CaptionResult]:
        """Fetch a specific subtitle track.

        Tries formats in preference order (US-006). Falls back to next format
        on parse error, not just unavailability.

        Args:
            video_url: Full YouTube URL.
            video_id: Video ID for result metadata.
            temp_dir: Temporary directory for downloaded files.
            language: Language code.
            auto_generated: Whether to fetch auto-generated captions.

        Returns:
            CaptionResult if successful, None if no captions for this format.
        """
        # Try each format in preference order (US-006)
        last_error = None
        for fmt in self._preferred_formats:
            try:
                result = self._fetch_subtitle_with_format(
                    video_url, video_id, temp_dir, language, auto_generated, fmt
                )
                if result and result.segments:
                    logger.info(
                        f"Caption {video_id}: Using {fmt} format "
                        f"({len(result.segments)} segments)"
                    )
                    return result
            except CaptionUnavailableError:
                # No captions in this format, try next
                logger.debug(f"Caption {video_id}: {fmt} format unavailable, trying next")
                continue
            except CaptionFetchError as e:
                # Parse or fetch error - try next format (US-006)
                last_error = e
                logger.debug(
                    f"Caption {video_id}: {fmt} format failed ({e.reason}), trying next"
                )
                continue

        # All formats exhausted
        if last_error:
            raise last_error
        return None

    def _fetch_subtitle_with_format(
        self,
        video_url: str,
        video_id: str,
        temp_dir: Path,
        language: str,
        auto_generated: bool,
        subtitle_format: str
    ) -> Optional[CaptionResult]:
        """Fetch subtitle in a specific format.

        Args:
            video_url: Full YouTube URL.
            video_id: Video ID for result metadata.
            temp_dir: Temporary directory for downloaded files.
            language: Language code.
            auto_generated: Whether to fetch auto-generated captions.
            subtitle_format: Format to request (json3, vtt, srt).

        Returns:
            CaptionResult if successful, None if no captions for this format.
        """
        # Build yt-dlp command
        sub_flag = '--write-auto-subs' if auto_generated else '--write-subs'
        output_template = str(temp_dir / '%(id)s.%(ext)s')

        cmd = [
            'yt-dlp',
            video_url,
            '--skip-download',  # Don't download video
            sub_flag,
            '--sub-lang', language,
            '--sub-format', subtitle_format,  # Request specific format (US-006)
            '-o', output_template,
            '--no-playlist',
            '--no-warnings',
        ]

        # Add impersonation args before cookies for correct argument ordering
        if self.impersonation_manager:
            imp_args = self.impersonation_manager.get_impersonate_args()
            if imp_args:
                cmd.extend(imp_args)

        # Add cookies if configured
        cmd.extend(self._get_cookies_args())

        try:
            result = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                timeout=self._timeout
            )

            # Check for errors indicating no captions
            if result.returncode != 0:
                stderr_lower = result.stderr.lower()
                if any(phrase in stderr_lower for phrase in [
                    'no subtitles',
                    'no automatic captions',
                    'subtitles are disabled',
                    'video unavailable',
                    'private video',
                ]):
                    raise CaptionUnavailableError(video_id, result.stderr[:200])
                else:
                    raise CaptionFetchError(video_id, result.stderr[:200])

            # Find downloaded subtitle file - look for the specific format first
            format_ext = f".{subtitle_format}"
            sub_files = list(temp_dir.glob(f"{video_id}*{format_ext}"))
            if not sub_files:
                # Try other extensions as fallback
                sub_files = list(temp_dir.glob(f"{video_id}*"))
                sub_files = [f for f in sub_files if f.suffix in ['.vtt', '.srt', '.json3', '.srv3', '.json']]

            if not sub_files:
                return None  # No subtitle file created

            sub_file = sub_files[0]
            logger.debug(f"Found subtitle file: {sub_file}")

            # Parse the subtitle file with error recovery (US-001 Sprint 7)
            parse_result = self._parse_subtitle_file(sub_file, video_id)

            if not parse_result.segments:
                return None

            # Determine format from filename
            format_source = sub_file.suffix.lstrip('.')

            # Set partial_recovery flag if segments were skipped but we still have valid results
            partial_recovery = parse_result.has_skipped and len(parse_result.segments) > 0

            return CaptionResult(
                video_id=video_id,
                segments=parse_result.segments,
                language=language,
                is_auto_generated=auto_generated,
                format_source=format_source,
                skipped_segments=parse_result.skipped_segments,
                partial_recovery=partial_recovery
            )

        except subprocess.TimeoutExpired:
            raise CaptionFetchError(video_id, f"Timeout after {self._timeout}s")
        except (CaptionUnavailableError, CaptionFetchError):
            raise
        except Exception as e:
            raise CaptionFetchError(video_id, str(e))

    def _parse_subtitle_file(
        self,
        file_path: Path,
        video_id: str
    ) -> ParseResult:
        """Parse a subtitle file into segments with error recovery.

        Supports VTT, SRT, and JSON3/SRV3 formats.

        Args:
            file_path: Path to subtitle file.
            video_id: Video ID for segment source_file field.

        Returns:
            ParseResult with segments and any skipped segment info (US-001 Sprint 7).
        """
        suffix = file_path.suffix.lower()

        try:
            content = file_path.read_text(encoding='utf-8')
        except UnicodeDecodeError:
            content = file_path.read_text(encoding='utf-8', errors='replace')

        if suffix == '.vtt':
            return self._parse_vtt(content, video_id)
        elif suffix == '.srt':
            return self._parse_srt(content, video_id)
        elif suffix in ['.json3', '.srv3', '.json']:
            return self._parse_json3(content, video_id)
        else:
            logger.warning(f"Unknown subtitle format: {suffix}, trying VTT parser")
            return self._parse_vtt(content, video_id)

    def _parse_vtt(self, content: str, video_id: str) -> ParseResult:
        """Parse VTT (WebVTT) format captions with segment-level error recovery.

        VTT format:
            WEBVTT

            00:00:01.000 --> 00:00:04.000
            Hello, world!

            00:00:05.000 --> 00:00:08.000
            This is a test.

        Error Recovery (US-001 Sprint 7):
            Individual segment parsing errors are caught and logged, allowing
            the parser to continue with remaining segments. Skipped segments
            are recorded with their index and error reason.

        Returns:
            ParseResult with segments and any skipped segment info.
        """
        segments = []
        skipped_segments = []
        lines = content.split('\n')

        # Skip header
        i = 0
        while i < len(lines) and '-->' not in lines[i]:
            i += 1

        # VTT timestamp pattern: HH:MM:SS.mmm or MM:SS.mmm
        timestamp_pattern = re.compile(
            r'(\d{1,2}:)?(\d{2}):(\d{2})[.,](\d{3})\s*-->\s*(\d{1,2}:)?(\d{2}):(\d{2})[.,](\d{3})'
        )

        current_index = 0
        segment_count = 0  # Track total segments attempted
        while i < len(lines):
            line = lines[i].strip()

            match = timestamp_pattern.search(line)
            if match:
                segment_count += 1
                segment_start_line = i
                try:
                    # Parse timestamps
                    start_time = self._parse_timestamp(match.group(0).split('-->')[0].strip())
                    end_time = self._parse_timestamp(match.group(0).split('-->')[1].strip())

                    if start_time is None or end_time is None:
                        raise ValueError(f"Invalid timestamp at line {i + 1}")

                    # Collect text lines until empty line or next timestamp
                    i += 1
                    text_lines = []
                    while i < len(lines):
                        text_line = lines[i].strip()
                        if not text_line:
                            i += 1
                            break
                        if timestamp_pattern.search(text_line):
                            break
                        # Skip VTT style tags
                        text_line = re.sub(r'<[^>]+>', '', text_line)
                        if text_line:
                            text_lines.append(text_line)
                        i += 1

                    text = ' '.join(text_lines).strip()
                    if text:
                        segments.append(CaptionSegment(
                            index=current_index,
                            start_time=start_time,
                            end_time=end_time,
                            text=text,
                            source_file=video_id
                        ))
                        current_index += 1
                    # Empty text is not an error, just skip silently
                except Exception as e:
                    reason = f"Parse error: {str(e)}"
                    skipped_segments.append((segment_count - 1, reason))
                    logger.debug(f"[{video_id}] Skipped VTT segment {segment_count - 1}: {reason}")
                    # Advance to next timestamp or empty line to continue parsing
                    while i < len(lines) and lines[i].strip() and not timestamp_pattern.search(lines[i]):
                        i += 1
            else:
                i += 1

        if skipped_segments:
            logger.info(
                f"[{video_id}] VTT parse: {len(segments)} segments parsed, "
                f"{len(skipped_segments)} skipped"
            )

        return ParseResult(
            segments=segments,
            skipped_segments=skipped_segments,
            total_attempted=segment_count
        )

    def _parse_srt(self, content: str, video_id: str) -> ParseResult:
        """Parse SRT (SubRip) format captions with segment-level error recovery.

        SRT format:
            1
            00:00:01,000 --> 00:00:04,000
            Hello, world!

            2
            00:00:05,000 --> 00:00:08,000
            This is a test.

        Error Recovery (US-001 Sprint 7):
            Individual block parsing errors are caught and logged, allowing
            the parser to continue with remaining blocks. Skipped blocks
            are recorded with their index and error reason.

        Returns:
            ParseResult with segments and any skipped segment info.
        """
        segments = []
        skipped_segments = []
        blocks = re.split(r'\n\s*\n', content.strip())

        for block_idx, block in enumerate(blocks):
            try:
                lines = block.strip().split('\n')
                if len(lines) < 2:
                    continue

                # Find timestamp line
                timestamp_line = None
                text_start_idx = 0
                for idx, line in enumerate(lines):
                    if '-->' in line:
                        timestamp_line = line
                        text_start_idx = idx + 1
                        break

                if not timestamp_line:
                    continue

                # Parse timestamps
                parts = timestamp_line.split('-->')
                if len(parts) != 2:
                    raise ValueError(f"Invalid timestamp format: {timestamp_line}")

                start_time = self._parse_timestamp(parts[0].strip())
                end_time = self._parse_timestamp(parts[1].strip())

                if start_time is None or end_time is None:
                    raise ValueError(f"Could not parse timestamps: {timestamp_line}")

                # Get text
                text = ' '.join(lines[text_start_idx:]).strip()
                text = re.sub(r'<[^>]+>', '', text)  # Remove tags

                if text:
                    segments.append(CaptionSegment(
                        index=len(segments),
                        start_time=start_time,
                        end_time=end_time,
                        text=text,
                        source_file=video_id
                    ))
                # Empty text after timestamp is not an error, just skip
            except Exception as e:
                reason = f"Parse error: {str(e)}"
                skipped_segments.append((block_idx, reason))
                logger.debug(f"[{video_id}] Skipped SRT block {block_idx}: {reason}")
                continue

        if skipped_segments:
            logger.info(
                f"[{video_id}] SRT parse: {len(segments)} segments parsed, "
                f"{len(skipped_segments)} skipped"
            )

        return ParseResult(
            segments=segments,
            skipped_segments=skipped_segments,
            total_attempted=len(blocks)
        )

    def _parse_json3(self, content: str, video_id: str) -> ParseResult:
        """Parse JSON3/SRV3 format captions from YouTube with error recovery.

        JSON3 format has 'events' array with 'segs' containing text segments.

        Error Recovery (US-001 Sprint 7):
            Events with missing required fields (tStartMs, segs) are skipped
            and logged. Other events continue to be processed.

        Returns:
            ParseResult with segments and any skipped event info.
        """
        skipped_segments = []

        try:
            data = json.loads(content)
        except json.JSONDecodeError as e:
            logger.warning(f"[{video_id}] Failed to parse JSON3 caption format: {e}")
            return ParseResult(
                segments=[],
                skipped_segments=[(0, f"JSON decode error: {str(e)}")],
                total_attempted=1
            )

        segments = []
        events = data.get('events', [])

        for event_idx, event in enumerate(events):
            try:
                # Check for required fields per acceptance criteria
                if 'segs' not in event:
                    skipped_segments.append((event_idx, "Missing 'segs' field"))
                    logger.debug(f"[{video_id}] Skipped JSON3 event {event_idx}: Missing 'segs' field")
                    continue

                if 'tStartMs' not in event:
                    skipped_segments.append((event_idx, "Missing 'tStartMs' field"))
                    logger.debug(f"[{video_id}] Skipped JSON3 event {event_idx}: Missing 'tStartMs' field")
                    continue

                start_ms = event['tStartMs']
                duration_ms = event.get('dDurationMs', 0)

                # Validate numeric types
                if not isinstance(start_ms, (int, float)):
                    raise ValueError(f"tStartMs is not numeric: {type(start_ms)}")

                # Combine all segs text
                text_parts = []
                for seg in event['segs']:
                    if 'utf8' in seg:
                        text_parts.append(seg['utf8'])

                text = ''.join(text_parts).strip()
                text = text.replace('\n', ' ')

                if text:
                    segments.append(CaptionSegment(
                        index=len(segments),
                        start_time=start_ms / 1000.0,
                        end_time=(start_ms + duration_ms) / 1000.0,
                        text=text,
                        source_file=video_id
                    ))
                # Empty text events are not errors, just skip
            except Exception as e:
                reason = f"Parse error: {str(e)}"
                skipped_segments.append((event_idx, reason))
                logger.debug(f"[{video_id}] Skipped JSON3 event {event_idx}: {reason}")
                continue

        if skipped_segments:
            logger.info(
                f"[{video_id}] JSON3 parse: {len(segments)} segments parsed, "
                f"{len(skipped_segments)} skipped"
            )

        return ParseResult(
            segments=segments,
            skipped_segments=skipped_segments,
            total_attempted=len(events) if events else 1
        )

    def _parse_timestamp(self, ts: str) -> Optional[float]:
        """Parse a timestamp string to seconds.

        Supports formats:
            HH:MM:SS,mmm (SRT)
            HH:MM:SS.mmm (VTT)
            MM:SS.mmm (VTT short)
        """
        ts = ts.strip()

        # Replace comma with period for SRT format
        ts = ts.replace(',', '.')

        # Pattern for HH:MM:SS.mmm or MM:SS.mmm
        match = re.match(r'^(?:(\d+):)?(\d+):(\d+)\.(\d+)$', ts)
        if match:
            hours = int(match.group(1)) if match.group(1) else 0
            minutes = int(match.group(2))
            seconds = int(match.group(3))
            millis = int(match.group(4).ljust(3, '0')[:3])  # Ensure 3 digits

            return hours * 3600 + minutes * 60 + seconds + millis / 1000.0

        # Try simpler pattern without milliseconds
        match = re.match(r'^(?:(\d+):)?(\d+):(\d+)$', ts)
        if match:
            hours = int(match.group(1)) if match.group(1) else 0
            minutes = int(match.group(2))
            seconds = int(match.group(3))
            return hours * 3600 + minutes * 60 + seconds

        logger.warning(f"Could not parse timestamp: {ts}")
        return None

    def _get_cookies_args(self) -> List[str]:
        """Get yt-dlp cookie arguments from config."""
        if not self.config:
            return []

        try:
            download_config = self.config.download

            # Prefer browser cookies
            cookies_browser = getattr(download_config, 'cookies_from_browser', '')
            if cookies_browser:
                return ['--cookies-from-browser', cookies_browser]

            # Fall back to cookies file
            cookies_path = getattr(download_config, 'cookies_path', '')
            if cookies_path and Path(cookies_path).exists():
                return ['--cookies', cookies_path]
        except AttributeError:
            pass

        return []

    def _is_valid_video_id(self, video_id: str) -> bool:
        """Validate YouTube video ID format.

        YouTube IDs are 11 characters: [A-Za-z0-9_-]
        """
        if not video_id or len(video_id) != 11:
            return False
        return bool(re.match(r'^[A-Za-z0-9_-]{11}$', video_id))

    def is_live_stream(self, video_id: str, timeout: Optional[int] = None) -> bool:
        """Check if a video is a live stream or was a live stream.

        Implements US-002: Live stream detection to skip caption fetch.
        Uses yt-dlp --dump-json to get video metadata and check is_live/was_live fields.

        Live streams can hang indefinitely during caption fetch because they either:
        - Are currently live (captions still being generated)
        - Were live but captions may be incomplete or unavailable

        Args:
            video_id: YouTube video ID (11 characters).
            timeout: Timeout for metadata fetch in seconds. If None, uses self._timeout.

        Returns:
            True if video is live or was live, False otherwise.

        Example:
            fetcher = CaptionFetcher()
            if fetcher.is_live_stream("dQw4w9WgXcQ"):
                print("Skipping live stream")
            else:
                result = fetcher.fetch_captions("dQw4w9WgXcQ")
        """
        if not self._is_valid_video_id(video_id):
            logger.debug(f"Invalid video ID for live stream check: {video_id}")
            return False

        video_url = f"https://www.youtube.com/watch?v={video_id}"
        fetch_timeout = timeout if timeout is not None else self._timeout

        cmd = [
            'yt-dlp',
            video_url,
            '--skip-download',
            '--dump-json',
            '--no-playlist',
            '--no-warnings',
        ]

        # Add impersonation args before cookies for correct argument ordering
        if self.impersonation_manager:
            imp_args = self.impersonation_manager.get_impersonate_args()
            if imp_args:
                cmd.extend(imp_args)

        # Add cookies if configured
        cmd.extend(self._get_cookies_args())

        try:
            result = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                timeout=fetch_timeout
            )

            if result.returncode != 0:
                # Could not fetch metadata, assume not live to avoid blocking
                logger.debug(
                    f"Could not fetch metadata for {video_id}: {result.stderr[:100]}"
                )
                return False

            # Parse JSON output
            try:
                metadata = json.loads(result.stdout)
            except json.JSONDecodeError as e:
                logger.debug(f"Failed to parse metadata JSON for {video_id}: {e}")
                return False

            # Check is_live and was_live fields
            is_live = metadata.get('is_live', False)
            was_live = metadata.get('was_live', False)

            if is_live or was_live:
                logger.info(
                    f"Video {video_id} is a live stream "
                    f"(is_live={is_live}, was_live={was_live})"
                )
                return True

            return False

        except subprocess.TimeoutExpired:
            logger.warning(
                f"Timeout checking live stream status for {video_id} "
                f"(treating as not live)"
            )
            return False
        except Exception as e:
            logger.debug(f"Error checking live stream status for {video_id}: {e}")
            return False

    def get_stream_state(
        self,
        video_id: str,
        timeout: Optional[int] = None
    ) -> StreamStateResult:
        """Get detailed stream state classification for a video (US-007 Sprint 8).

        Enhanced version of is_live_stream() that returns detailed state information
        including scheduled start times for UPCOMING/PREMIERE streams.

        Uses yt-dlp metadata to classify into:
        - LIVE: Currently streaming
        - UPCOMING: Scheduled live stream (not yet started)
        - VOD: Regular video-on-demand
        - PREMIERE: Scheduled premiere (pre-recorded with countdown)
        - UNKNOWN: Could not determine (metadata fetch failed)

        Args:
            video_id: YouTube video ID (11 characters).
            timeout: Timeout for metadata fetch in seconds. If None, uses self._timeout.

        Returns:
            StreamStateResult with state classification and metadata.

        Example:
            >>> fetcher = CaptionFetcher()
            >>> result = fetcher.get_stream_state("dQw4w9WgXcQ")
            >>> if result.state == StreamState.LIVE:
            ...     print("Skipping live stream")
            >>> elif result.state == StreamState.UPCOMING:
            ...     print(f"Queuing: scheduled {result.scheduled_start}")
            >>> print(result)  # "dQw4w9WgXcQ: UPCOMING (scheduled 2026-01-27 10:00 UTC)"
        """
        if not self._is_valid_video_id(video_id):
            logger.debug(f"Invalid video ID for stream state check: {video_id}")
            return StreamStateResult(
                state=StreamState.UNKNOWN,
                video_id=video_id,
            )

        video_url = f"https://www.youtube.com/watch?v={video_id}"
        fetch_timeout = timeout if timeout is not None else self._timeout

        cmd = [
            'yt-dlp',
            video_url,
            '--skip-download',
            '--dump-json',
            '--no-playlist',
            '--no-warnings',
        ]

        # Add impersonation args before cookies for correct argument ordering
        if self.impersonation_manager:
            imp_args = self.impersonation_manager.get_impersonate_args()
            if imp_args:
                cmd.extend(imp_args)

        # Add cookies if configured
        cmd.extend(self._get_cookies_args())

        try:
            result = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                timeout=fetch_timeout
            )

            if result.returncode != 0:
                # Could not fetch metadata
                logger.debug(
                    f"Could not fetch metadata for stream state {video_id}: "
                    f"{result.stderr[:100] if result.stderr else 'no error output'}"
                )
                return StreamStateResult(
                    state=StreamState.UNKNOWN,
                    video_id=video_id,
                )

            # Parse JSON output
            try:
                metadata = json.loads(result.stdout)
            except json.JSONDecodeError as e:
                logger.debug(f"Failed to parse metadata JSON for {video_id}: {e}")
                return StreamStateResult(
                    state=StreamState.UNKNOWN,
                    video_id=video_id,
                )

            # Classify stream state
            state_result = classify_stream_state(metadata, video_id)

            # Log the classification with details
            logger.info(f"Stream state: {state_result}")

            return state_result

        except subprocess.TimeoutExpired:
            logger.warning(
                f"Timeout checking stream state for {video_id} (treating as UNKNOWN)"
            )
            return StreamStateResult(
                state=StreamState.UNKNOWN,
                video_id=video_id,
            )
        except Exception as e:
            logger.debug(f"Error checking stream state for {video_id}: {e}")
            return StreamStateResult(
                state=StreamState.UNKNOWN,
                video_id=video_id,
            )

