    def test_auto_fallback_records_metrics(self):
        """Auto fallback records auto_fallback_count in metrics.

        AC US-62-005: Metrics track count of videos using auto-generated vs manual captions.
        When auto-generated fallback is used, auto_fallback_count should be incremented.
        """
        from src.caption.metrics import CaptionMetrics

        fetcher = CaptionFetcher()
        auto_result = _make_caption_result(is_auto=True)
        metrics = CaptionMetrics()

        # Set the metrics reference on the fetcher
        fetcher._active_metrics = metrics

        with patch.object(fetcher, 'list_available_languages', return_value=[
            AvailableLanguage(code='en', name='English', is_auto_generated=True),
        ]):
            def mock_format(video_url, video_id, temp_dir, language,
                            auto_generated, fmt, fallback_level=0):
                if not auto_generated:
                    raise CaptionUnavailableError(video_id, "no subtitles")
                return auto_result

            with patch.object(fetcher, '_fetch_subtitle_with_format',
                              side_effect=mock_format):
                with tempfile.TemporaryDirectory() as td:
                    result = fetcher._fetch_subtitle(
                        "https://www.youtube.com/watch?v=dQw4w9WgXcQ",
                        "dQw4w9WgXcQ",
                        Path(td),
                        "en",
                        False,
                    )

                    # Verify result is auto-generated
                    assert result is not None
                    assert result.is_auto_generated is True

                    # Verify metrics were recorded
                    assert metrics.auto_fallback_count == 1

