    def test_no_fallback_when_already_auto(self):
        """When called with auto_generated=True already, no redundant retry."""
        fetcher = CaptionFetcher()

        with patch.object(fetcher, 'list_available_languages', return_value=[
            AvailableLanguage(code='en', name='English', is_auto_generated=True),
        ]):
            call_count = 0

            def mock_format(video_url, video_id, temp_dir, language,
                            auto_generated, fmt, fallback_level=0):
                nonlocal call_count
                call_count += 1
                raise CaptionUnavailableError(video_id, "no subtitles")

            with patch.object(fetcher, '_fetch_subtitle_with_format',
                              side_effect=mock_format):
                with tempfile.TemporaryDirectory() as td:
                    with pytest.raises(CaptionUnavailableError):
                        fetcher._fetch_subtitle(
                            "https://www.youtube.com/watch?v=dQw4w9WgXcQ",
                            "dQw4w9WgXcQ",
                            Path(td),
                            "en",
                            True,  # Already requesting auto
                        )

                    # Should only try formats once (no fallback loop)
                    # 1 call per format (3 formats) = 3 max, but CaptionUnavailableError
                    # breaks the loop immediately, so only 1 call
                    assert call_count == 1

